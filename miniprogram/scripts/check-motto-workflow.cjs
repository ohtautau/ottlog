const path = require('node:path');

module.exports = async function checkMottoWorkflow({ page, origin, out, width, expect, checkCreateButton }) {
  const quote = () => page.locator('.today-quote');
  const row = index => page.getByRole('button', { name: `编辑第 ${index} 句格言`, exact: true });
  const editor = () => page.locator('.mottos-editor-sheet');
  const input = () => page.getByRole('textbox', { name: '格言内容', exact: true });
  const add = () => page.locator('.mottos-heading').getByRole('button', { name: '创建格言', exact: true });
  const close = () => page.getByRole('button', { name: '关闭格言编辑', exact: true }).click();
  const prompt = () => page.getByRole('dialog', { name: '保存修改？', exact: true });
  const texts = () => page.locator('.mottos-text').allTextContents();
  await page.clock.install({ time: new Date('2026-09-16T12:00:00') });
  await page.goto(`${origin}/?mottos-${width}#/pages/index/index`);
  await expect(quote().locator('.today-quote-count')).toContainText('/03');
  await expect(quote().locator('.today-quote-heading')).toHaveCount(0);
  await expect(quote()).not.toContainText('此刻的一句话');
  await expect(quote()).not.toContainText('WORDS TO LIVE BY');
  await expect(quote().getByRole('button')).toHaveCount(1);
  await expect(quote().locator('.today-quote-controls,.today-quote-footer,.today-quote-play-icon,.today-quote-pause-icon')).toHaveCount(0);
  await expect(quote().locator('.today-quote-manage .edit-symbol')).toBeVisible();
  const quoteLayout = await quote().evaluate(node => {
    const box = target => { const r = target.getBoundingClientRect(); return { left: r.left, right: r.right, top: r.top, bottom: r.bottom, width: r.width, height: r.height }; };
    const style = getComputedStyle(node);
    const text = node.querySelector('.today-quote-text'), textStyle = getComputedStyle(text);
    return { quote: box(node), body: box(node.querySelector('.today-quote-body')), side: box(node.querySelector('.today-quote-side')), content: box(node.querySelector('.today-quote-content')), text: box(text), count: box(node.querySelector('.today-quote-count')), manage: box(node.querySelector('.today-quote-manage')), paddingLeft: parseFloat(style.paddingLeft), font: parseFloat(textStyle.fontSize), line: parseFloat(textStyle.lineHeight), overflow: node.scrollWidth - node.clientWidth };
  });
  expect(quoteLayout.paddingLeft).toBe(16);
  expect(quoteLayout.overflow).toBeLessThanOrEqual(1);
  expect(quoteLayout.manage.width).toBeGreaterThanOrEqual(40); expect(quoteLayout.manage.height).toBeGreaterThanOrEqual(40);
  expect(quoteLayout.font).toBe(width >= 600 ? 16 : 15);
  expect(quoteLayout.line).toBe(width >= 600 ? 24 : 23);
  expect(quoteLayout.content.height).toBeCloseTo(quoteLayout.line * 2, 0);
  expect(quoteLayout.count.top).toBeCloseTo(quoteLayout.manage.bottom + 4, 0);
  expect((quoteLayout.count.left + quoteLayout.count.right) / 2).toBeCloseTo((quoteLayout.manage.left + quoteLayout.manage.right) / 2, 0);
  expect(quoteLayout.side.left).toBeCloseTo(quoteLayout.body.right + 12, 0);
  expect((quoteLayout.side.top + quoteLayout.side.bottom) / 2).toBeCloseTo((quoteLayout.quote.top + quoteLayout.quote.bottom) / 2, 0);
  expect((quoteLayout.content.top + quoteLayout.content.bottom) / 2).toBeCloseTo((quoteLayout.quote.top + quoteLayout.quote.bottom) / 2, 0);
  expect((quoteLayout.text.top + quoteLayout.text.bottom) / 2).toBeCloseTo((quoteLayout.content.top + quoteLayout.content.bottom) / 2, 0);
  await page.screenshot({ path: path.join(out, `motto-banner-${width}.png`) });
  await quote().dispatchEvent('touchstart', { touches: [{ identifier: 1, clientX: 100, clientY: 150 }] });
  const first = await quote().locator('.today-quote-text').textContent();
  await page.clock.runFor(30000);
  await expect(quote().locator('.today-quote-text')).toHaveText(first);
  await quote().dispatchEvent('touchend', { touches: [] });
  await page.clock.runFor(14000);
  await expect(quote().locator('.today-quote-text')).toHaveText(first);
  await page.clock.runFor(1100);
  await expect(quote().locator('.today-quote-text')).not.toHaveText(first);
  await quote().getByRole('button', { name: '管理格言', exact: true }).click();
  await expect(page).toHaveURL(/pages\/mottos\/index/);
  await expect(page.locator('.mottos-row')).toHaveCount(3);
  await expect(page.locator('.mottos-count')).toHaveText('3 句');
  await expect(add()).toBeEnabled();
  await checkCreateButton(add(), '创建格言', expect);
  const original = await texts();
  const added = '慢慢走，也一直向前。';
  const revised = '给自己一点安静，也给想法一点时间。';
  await add().click(); await close(); await expect(editor()).toHaveCount(0); await expect(prompt()).toHaveCount(0);
  await add().click();
  await expect(editor()).toBeVisible();
  await expect(editor()).not.toContainText('换一句');
  await expect(editor().getByRole('button', { name: '创建格言', exact: true })).toBeDisabled();
  await input().fill(added);
  const layout = await editor().evaluate(node => {
    const sheet = node.getBoundingClientRect(), viewport = document.querySelector('.preview-content').getBoundingClientRect(), footer = node.querySelector('.mottos-editor-footer').getBoundingClientRect();
    return { top: sheet.top, bottom: sheet.bottom, footer: footer.bottom, viewTop: viewport.top, viewBottom: viewport.bottom, overflow: node.scrollWidth - node.clientWidth };
  });
  expect(layout.top).toBeGreaterThanOrEqual(layout.viewTop - 1);
  expect(layout.bottom).toBeLessThanOrEqual(layout.viewBottom + 1);
  expect(layout.footer).toBeLessThanOrEqual(layout.viewBottom + 1);
  expect(layout.overflow).toBeLessThanOrEqual(2);
  await page.screenshot({ path: path.join(out, `motto-editor-${width}.png`) });
  await close(); await expect(prompt()).toBeVisible();
  await prompt().getByRole('button', { name: '继续编辑', exact: true }).click();
  await expect(input()).toHaveValue(added); await expect(prompt()).toHaveCount(0);
  await close(); await page.evaluate(() => { window.__miniFixture.failToolWrites = ['mottos']; });
  await prompt().getByRole('button', { name: '保存', exact: true }).click();
  await expect(prompt()).toHaveCount(0); await expect(editor()).toBeVisible();
  await expect(input()).toHaveValue(added); await expect(input()).toBeDisabled();
  await expect(page.locator('.mottos-message')).toContainText('本机存储不可用');
  await page.evaluate(() => { window.__miniFixture.failToolWrites = []; });
  await close(); await prompt().getByRole('button', { name: '保存', exact: true }).click();
  await expect(editor()).toHaveCount(0);
  expect(await texts()).toEqual([...original, added]);
  await add().click(); await input().fill(added);
  await editor().getByRole('button', { name: '创建格言', exact: true }).click();
  await expect(page.locator('.mottos-message')).toContainText('已经存在');
  await close(); await expect(prompt()).toBeVisible(); await prompt().getByRole('button', { name: '不保存', exact: true }).click();
  await row(1).click(); await input().fill(revised);
  await close(); await expect(prompt()).toBeVisible(); await prompt().getByRole('button', { name: '保存', exact: true }).click();
  await expect(row(1)).toContainText(revised);
  await row(1).click(); await input().fill('取消后不应该保存'); await close();
  await expect(prompt()).toBeVisible(); await prompt().getByRole('button', { name: '不保存', exact: true }).click();
  await expect(row(1)).toContainText(revised);
  await page.screenshot({ path: path.join(out, `motto-list-${width}.png`) });
  await page.evaluate(() => { location.hash = '#/pages/index/index'; });
  await expect(quote().locator('.today-quote-count')).toContainText('/04');
  await quote().getByRole('button', { name: '管理格言', exact: true }).click();
  await expect(page.locator('.mottos-text')).toHaveText([revised, ...original.slice(1), added]);
  await row(4).click();
  await editor().getByRole('button', { name: '删除格言', exact: true }).click();
  await page.getByRole('dialog', { name: '删除这句格言？', exact: true }).getByRole('button', { name: '关闭提示', exact: true }).click();
  await expect(editor()).toBeVisible();
  await expect(editor().getByRole('button', { name: '删除格言', exact: true })).toBeEnabled();
  await editor().getByRole('button', { name: '删除格言', exact: true }).click();
  await page.getByRole('dialog', { name: '删除这句格言？', exact: true }).getByRole('button', { name: '删除', exact: true }).click();
  await expect(editor()).toHaveCount(0);
  expect(await texts()).toEqual([revised, ...original.slice(1)]);
  expect(await page.evaluate(() => window.__miniRequests.filter(request => request.path === '/mottos' && request.method !== 'GET'))).toEqual([]);

  // The standalone management screen keeps its actions in place with long lists.
  await page.goto(`${origin}/?mottos-scroll-${width}#/pages/posts/index`);
  await page.evaluate(() => {
    localStorage.removeItem('ottlog-mini-tool-v1:guest:mottos');
    window.__miniFixture.persistEntryTools = true;
    window.__miniFixture.mottos = Array.from({ length: 60 }, (_, index) => `第 ${index + 1} 句：每一个小小的行动，都在为生活留下一点光。`);
    location.hash = '#/pages/mottos/index';
  });
  await expect(page.locator('.mottos-row')).toHaveCount(60);
  await expect(page.locator('.mottos-count')).toHaveText('60 句');
  await expect(add()).toBeEnabled();
  const scroll = page.locator('.mottos-list-scroll');
  expect(await scroll.evaluate(node => node.scrollHeight - node.clientHeight)).toBeGreaterThan(100);
  await scroll.evaluate(node => { node.scrollTop = node.scrollHeight; });
  await expect(row(60)).toBeInViewport();
  await expect(add()).toBeInViewport();
  await expect(page.locator('.mottos-status'), 'Normal guest storage information is centralized in My by C83').toHaveCount(0);
  expect(await page.locator('.mottos-page').evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(2);
  await page.screenshot({ path: path.join(out, `motto-list-scroll-${width}.png`) });
  await add().click(); await input().fill('第61句：数量上限已取消。');
  await editor().getByRole('button', { name: '创建格言', exact: true }).click();
  await expect(editor()).toHaveCount(0);
  await expect(page.locator('.mottos-count')).toHaveText('61 句');
  await expect(add()).toBeEnabled();
  await page.reload();
  await expect(page.locator('.mottos-row')).toHaveCount(61);
  await expect(page.locator('.mottos-count')).toHaveText('61 句');
  await scroll.evaluate(node => { node.scrollTop = node.scrollHeight; });
  await expect(row(61)).toBeInViewport();
  await expect(row(61)).toContainText('第61句：数量上限已取消。');
  await require('./check-motto-rotation.cjs')({ page, origin, out, width, expect });
  const longMotto = '保留完整格言内容，较长文字在首页按两行显示。'.repeat(5);
  for (const [name, mottos] of [['long', [longMotto]], ['single', ['一句格言']], ['empty', []]]) {
    const data = { version: 1, mottos, rotationSeconds: 4 };
    await page.evaluate(data => localStorage.setItem('ottlog-mini-tool-v1:guest:mottos', JSON.stringify({ data, pending: false, revision: 1 })), data);
    await page.goto(`${origin}/?motto-banner-${name}-${width}#/pages/index/index`);
    await expect(quote().locator('.today-quote-text')).toHaveText(mottos[0] || '暂无格言');
    await expect(quote().locator('.today-quote-count')).toContainText(mottos.length ? '/01' : '/00');
    await expect(quote().getByRole('button')).toHaveCount(1);
    const layout = await quote().locator('.today-quote-text').evaluate(node => ({ height: node.getBoundingClientRect().height, line: parseFloat(getComputedStyle(node).lineHeight), quoteHeight: node.closest('.today-quote').getBoundingClientRect().height }));
    expect(layout.height).toBeCloseTo(layout.line * (name === 'long' ? 2 : 1), 0);
    expect(layout.quoteHeight).toBeCloseTo(quoteLayout.quote.height, 0);
    await page.clock.runFor(16000);
    await expect(quote().locator('.today-quote-text')).toHaveText(mottos[0] || '暂无格言');
    expect(await page.evaluate(() => window.__miniPreviewControl.readStorage('ottlog-mini-tool-v1:guest:mottos').data)).toEqual(data);
    await page.screenshot({ path: path.join(out, `motto-banner-${name}-${width}.png`) });
  }
};

const path = require('node:path');
const schedule = require('./todo-schedule-test-helpers.cjs');
module.exports = async function checkScheduleTime({ page, origin, out, width, expect }) {
  await page.clock.setFixedTime(new Date('2026-10-07T12:00:00'));
  await page.goto(`${origin}/?schedule-time-${width}#/pages/posts/index`);
  await page.evaluate(() => {
    document.documentElement.style.setProperty('--preview-safe-area-bottom', '34px');
    window.__miniFixture.sessionProfile = { authenticated: false, userName: null, isAdmin: false };
    window.__miniFixture.guestToolStates = { todos: { version: 1, tasks: [], categories: [] } };
    localStorage.removeItem('ottlog-mini-tool-v1:guest:todos');
    location.hash = '#/pages/todos/index';
  });
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('ottlog-mini-tool-v1:guest:todos') || '{"data":{"tasks":[]}}').data);
  await page.locator('.todo-quadrant-later .todo-quadrant-add').click();
  await page.getByPlaceholder('准备做什么？').fill('时间小窗验证');
  await schedule.openSchedule(page, expect);
  await schedule.button(page, '选择年月').click();
  await expect(page.locator('.todo-schedule-month-popover')).toHaveClass(/is-positioned/);
  await schedule.checkScheduleInputAlignment(page, expect, `${width} centered year/month`);
  await page.screenshot({ path: path.join(out, `schedule-month-centered-${width}.png`) });
  await schedule.button(page, '关闭年月选择').click();
  await schedule.selectDate(page, '2026-10-08');
  const row = schedule.button(page, '设置时间'), panel = page.locator('.todo-schedule-time-popover');
  const hour = () => panel.getByLabel('任务小时', { exact: true });
  const minute = () => panel.getByLabel('任务分钟', { exact: true });
  const prompt = () => page.getByRole('dialog', { name: '保存修改？', exact: true });
  const discard = () => require('./confirm-unsaved-close.cjs')(page);
  const done = () => panel.getByRole('button', { name: '完成时间设置', exact: true });
  const clearTime = () => schedule.button(page, '清除时间设置');
  const overview = () => schedule.sheet(page).locator('.todo-schedule-calendar,.todo-schedule-row,.todo-schedule-setting-clear,.todo-schedule-footer').evaluateAll(nodes => nodes.map(node => { const b = node.getBoundingClientRect(); return [b.x, b.y, b.width, b.height]; }));
  const beforeOverview = await overview();
  await expect(clearTime()).toHaveCount(0);
  await expect(schedule.button(page, '展开时间设置')).toBeVisible();
  await expect(row.locator('.select-chevron')).toHaveCount(0);
  await schedule.button(page, '展开时间设置').click();
  await expect(hour()).toHaveValue('09'); await expect(minute()).toHaveValue('00');
  await expect(panel.locator('.todo-schedule-popover-heading')).toHaveCount(1);
  await expect(panel.locator('.todo-schedule-choices')).toHaveCount(0);
  await expect(panel.getByRole('button', { name: '不设时间', exact: true })).toHaveCount(0);
  await expect(panel.getByRole('button')).toHaveCount(2);
  await panel.getByRole('button', { name: '关闭时间设置', exact: true }).click();
  await expect(panel).toHaveCount(0); await expect(prompt()).toHaveCount(0);
  await schedule.button(page, '展开时间设置').click();
  await schedule.checkScheduleLayout(page, expect, `${width} compact time`);
  const geometry = await panel.evaluate(node => {
    const box = node.getBoundingClientRect(), group = node.querySelector('.todo-schedule-clock-input');
    const first = group.firstElementChild.getBoundingClientRect(), last = group.lastElementChild.getBoundingClientRect();
    const prompt = () => page.getByRole('dialog', { name: '保存修改？', exact: true });
  const discard = () => require('./confirm-unsaved-close.cjs')(page);
  const done = node.querySelector('[aria-label="完成时间设置"]').getBoundingClientRect();
    return { center: (first.left + last.right - box.left - box.right) / 2, right: box.right - done.right,
      rowGap: done.top - first.bottom, height: done.height, panelHeight: box.height, headingHeight: node.querySelector('.editor-heading').getBoundingClientRect().height, actions: { x: done.x, y: done.y, width: done.width, height: done.height } };
  });
  expect(Math.abs(geometry.center), 'Actual time controls are centered, not just their container').toBeLessThanOrEqual(1);
  expect(geometry.right).toBeGreaterThanOrEqual(10); expect(geometry.right).toBeLessThanOrEqual(15);
  expect(geometry.rowGap).toBeGreaterThanOrEqual(0); expect(geometry.height).toBeGreaterThanOrEqual(40);
  expect(geometry.rowGap, 'Time controls and completion have no blank error row between them').toBeLessThanOrEqual(20);
  expect(geometry.panelHeight - geometry.headingHeight, 'The time fields and completion remain two compact rows below the shared title').toBeLessThanOrEqual(120);
  expect(await overview(), 'Opening time keeps the calendar/settings geometry').toEqual(beforeOverview);
  await panel.locator('.schedule-number-field').first().click({ position: { x: 3, y: 3 } });
  await expect(hour()).toBeFocused();
  await page.screenshot({ path: path.join(out, `schedule-time-default-${width}.png`) });
  for (const [h, m] of [['', '00'], ['09', ''], ['24', '00'], ['23', '60'], ['-1', '00'], ['1.5', '00'], ['1e2', '00'], ['100', '00'], ['09', '100']]) {
    await hour().fill(h); await minute().fill(m); await done().click();
    await expect(panel.locator('[role="alert"]')).toContainText('0–23');
    await expect(panel.locator('[role="alert"]')).toBeInViewport({ ratio: 1 });
    await expect(hour()).toHaveValue(h); await expect(minute()).toHaveValue(m);
    await expect(row).toContainText('未设置');
    expect(await done().boundingBox(), 'Invalid completion does not move the action').toEqual(geometry.actions);
    expect(await overview(), 'Time validation stays inside its window').toEqual(beforeOverview);
    expect((await stored()).tasks).toEqual([]);
  }
  await page.screenshot({ path: path.join(out, `schedule-time-invalid-${width}.png`) });
  await hour().fill('18'); await minute().fill('30');
  await panel.locator('..').locator('.form-popover-backdrop').click({ position: { x: 2, y: 2 } });
  await expect(prompt()).toBeVisible(); await prompt().getByRole('button', { name: '继续编辑', exact: true }).click();
  await expect(hour()).toHaveValue('18'); await expect(minute()).toHaveValue('30');
  await panel.getByRole('button', { name: '关闭时间设置', exact: true }).click();
  await expect(prompt()).toBeVisible(); await prompt().getByRole('button', { name: '不保存', exact: true }).click();
  await expect(panel).toHaveCount(0); await expect(row).toContainText('未设置');
  await row.click(); await expect(hour()).toHaveValue('18'); await expect(minute()).toHaveValue('30');
  await panel.getByRole('button', { name: '关闭时间设置', exact: true }).click();
  await prompt().getByRole('button', { name: '保存', exact: true }).click(); await expect(panel).toHaveCount(0); await expect(row).toContainText('18:30');
  await expect(clearTime()).toBeInViewport({ ratio: 1 });
  const clearBox = await clearTime().boundingBox(); expect(clearBox.width).toBeGreaterThanOrEqual(40); expect(clearBox.height).toBeGreaterThanOrEqual(40);
  expect(await overview(), 'Applying time preserves the clear slot and overview geometry').toEqual(beforeOverview);
  for (const [h, m, formatted] of [['0', '0', '00:00'], ['23', '59', '23:59'], ['1', '5', '01:05']]) {
    await schedule.setTime(page, h, m); await expect(row).toContainText(formatted);
  }
  await row.click(); await hour().fill('24'); await done().click();
  await page.keyboard.press('Escape'); await expect(prompt()).toBeVisible();
  await prompt().getByRole('button', { name: '保存', exact: true }).click();
  await expect(prompt()).toHaveCount(0); await expect(hour()).toHaveValue('24');
  await expect(panel.locator('[role="alert"]')).toContainText('0–23');
  await page.keyboard.press('Escape'); await discard(); await expect(panel).toHaveCount(0);
  await expect(schedule.sheet(page)).toBeVisible(); await expect(row).toContainText('01:05');
  await row.click(); await expect(hour()).toHaveValue('24');
  await page.keyboard.press('Escape'); await discard(); await clearTime().click();
  await expect(panel).toHaveCount(0); await expect(row).toContainText('未设置');
  await expect(clearTime()).toHaveCount(0);
  await expect(schedule.button(page, '展开时间设置')).toBeVisible();
  expect(await overview(), 'Clearing time preserves the calendar, all rows, clear slots and actions').toEqual(beforeOverview);
  await expect(schedule.button(page, '选择日期2026-10-08')).toHaveAttribute('aria-pressed', 'true');
  await row.click(); await expect(hour()).toHaveValue('01'); await expect(minute()).toHaveValue('05');
  await expect(panel.locator('[role="alert"]')).toHaveCount(0); await page.keyboard.press('Escape');
  await schedule.setTime(page, 9, 30);
  await schedule.openSection(page, '设置提醒'); await schedule.button(page, '准时').click();
  await schedule.closeOptionWindows(page);
  await schedule.openSection(page, '设置重复'); await schedule.button(page, '自定义重复').click();
  await expect(page.locator('.todo-schedule-repeat-popover')).toHaveClass(/is-centered/);
  await expect(page.getByLabel('重复间隔', { exact: true })).toBeInViewport({ ratio: 1 });
  await expect(page.locator('.is-repeat-units')).toHaveCount(0);
  const repeatUnit = () => schedule.button(page, '选择重复单位');
  const unitPanel = () => page.getByRole('dialog', { name: '选择重复单位', exact: true });
  await expect(repeatUnit()).toHaveText('天');
  await schedule.checkScheduleInputAlignment(page, expect, `${width} centered default every-one-day row`);
  await page.screenshot({ path: path.join(out, `schedule-repeat-unit-default-${width}.png`) });
  await page.getByLabel('重复间隔', { exact: true }).fill('2');
  for (const label of ['周', '月', '年', '工作日', '天']) {
    await repeatUnit().click(); await expect(unitPanel()).toHaveClass(/is-positioned/);
    await expect(unitPanel().locator('.form-option')).toHaveText(['天', '周', '月', '年', '工作日']);
    await unitPanel().getByRole('button', { name: label, exact: true }).click();
    await expect(unitPanel()).toHaveCount(0); await expect(repeatUnit()).toHaveText(label);
    await expect(page.getByLabel('重复间隔', { exact: true })).toHaveValue('2');
    await expect(page.locator('.todo-schedule-repeat-popover')).toHaveCount(1);
    await schedule.checkScheduleInputAlignment(page, expect, `${width} centered repeat unit ${label}`);
  }
  await repeatUnit().click(); await page.keyboard.press('Escape'); await expect(unitPanel()).toHaveCount(0);
  await expect(page.locator('.todo-schedule-repeat-popover')).toHaveCount(1); await expect(repeatUnit()).toHaveText('天');
  await repeatUnit().click(); await unitPanel().locator('..').locator('.form-popover-backdrop').click({ position: { x: 2, y: 2 } });
  await expect(unitPanel()).toHaveCount(0); await expect(repeatUnit()).toHaveText('天');
  await schedule.checkScheduleInputAlignment(page, expect, `${width} centered custom repeat`);
  await page.screenshot({ path: path.join(out, `schedule-repeat-centered-${width}.png`) });
  await repeatUnit().click(); await unitPanel().getByRole('button', { name: '月', exact: true }).click();
  await schedule.closeOptionWindows(page);
  await schedule.confirmSchedule(page, expect);
  await expect(page.locator('.todo-schedule-trigger')).toContainText('09:30');
  expect((await stored()).tasks).toEqual([]);
  await page.locator('.entry-composer').getByRole('button', { name: '创建任务', exact: true }).click();
  await expect.poll(async () => (await stored()).tasks.length).toBe(1);
  const saved = (await stored()).tasks[0]; expect(saved.dueDate).toBe('2026-10-08'); expect(saved.dueTime).toBe('09:30');
  expect(saved.recurrence).toMatchObject({ unit: 'month', interval: 2 });
  await expect(page.locator('.entry-composer')).toHaveCount(0);
  const reminder = saved.reminderAt;
  // Creation returns to the list; existing schedule edits start from the task's own entry.
  await page.getByRole('button', { name: '编辑任务：时间小窗验证', exact: true }).click();
  await expect(page.locator('.todo-sheet:not(.entry-composer)')).toBeVisible();
  await schedule.openSchedule(page, expect); await row.click();
  await expect(hour()).toHaveValue('09'); await expect(minute()).toHaveValue('30');
  await hour().fill('10'); await done().click(); await expect(row).toContainText('10:30');
  await schedule.closeSchedule(page, expect);
  await expect(page.locator('.todo-schedule-trigger')).toContainText('09:30');
  expect((await stored()).tasks[0]).toEqual(saved);
  await schedule.openSchedule(page, expect); await schedule.setTime(page, 10, 30);
  await schedule.confirmSchedule(page, expect);
  await page.locator('.todo-sheet:not(.entry-composer)').getByRole('button', { name: '保存', exact: true }).click();
  await expect.poll(async () => (await stored()).tasks[0].dueTime).toBe('10:30');
  const edited = (await stored()).tasks[0]; expect(edited.id).toBe(saved.id); expect(edited.reminderAt).toBe(reminder);
  await page.reload();
  await page.getByRole('button', { name: '编辑任务：时间小窗验证', exact: true }).click();
  await schedule.openSchedule(page, expect); await row.click();
  await expect(hour()).toHaveValue('10'); await expect(minute()).toHaveValue('30');
  await page.screenshot({ path: path.join(out, `schedule-time-saved-${width}.png`) });
  await hour().fill('24'); await done().click(); await page.keyboard.press('Escape'); await discard();
  const beforeClear = await overview();
  await clearTime().click(); await expect(row).toContainText('未设置'); await expect(clearTime()).toHaveCount(0);
  await expect(schedule.button(page, '选择日期2026-10-08')).toHaveAttribute('aria-pressed', 'true');
  await expect(schedule.button(page, '设置提醒')).toContainText('10月8日 09:30');
  await expect(schedule.button(page, '设置重复')).toContainText('每 2 月');
  expect(await overview(), 'Existing time clear does not move any overview control').toEqual(beforeClear);
  expect((await stored()).tasks[0], 'Clearing only changes the date-sheet draft').toEqual(edited);
  await schedule.closeSchedule(page, expect);
  await expect(page.locator('.todo-schedule-trigger')).toContainText('10:30');
  await schedule.openSchedule(page, expect); await expect(clearTime()).toBeVisible();
  await clearTime().click(); await schedule.confirmSchedule(page, expect);
  expect((await stored()).tasks[0], 'Date confirmation does not save the task').toEqual(edited);
  await expect(page.locator('.todo-schedule-trigger')).not.toContainText('10:30');
  await schedule.openSchedule(page, expect); await expect(clearTime()).toHaveCount(0);
  await row.click(); await expect(hour()).toHaveValue('09'); await expect(minute()).toHaveValue('00');
  await expect(panel.locator('[role="alert"]')).toHaveCount(0); await schedule.closeOptionWindows(page);
  await page.screenshot({ path: path.join(out, `schedule-time-cleared-${width}.png`) });
  await schedule.confirmSchedule(page, expect);
  await page.locator('.todo-sheet:not(.entry-composer)').getByRole('button', { name: '保存', exact: true }).click();
  await expect.poll(async () => (await stored()).tasks[0].dueTime).toBe(undefined);
  const cleared = (await stored()).tasks[0];
  for (const key of ['id', 'title', 'createdAt', 'dueDate', 'reminderAt', 'recurrence']) expect(cleared[key]).toEqual(edited[key]);
  expect(cleared.reminderAt).toBe(reminder);
  await page.reload(); await page.getByRole('button', { name: '编辑任务：时间小窗验证', exact: true }).click();
  await schedule.openSchedule(page, expect); await expect(row).toContainText('未设置'); await expect(clearTime()).toHaveCount(0);
  await row.click(); await hour().fill('24'); await done().click(); await page.keyboard.press('Escape'); await discard();
  await schedule.button(page, '清除日期设置').click(); await row.click();
  await expect(hour()).toHaveValue('09'); await expect(minute()).toHaveValue('00');
  await expect(panel.locator('[role="alert"]')).toHaveCount(0);
  await schedule.closeSchedule(page, expect);
  await expect(page.locator('.todo-schedule-trigger')).not.toContainText('10:30');
  expect((await stored()).tasks[0]).toEqual(cleared);
};

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const modules = new Map();
function load(name) {
  if (modules.has(name)) return modules.get(name).exports;
  const module = { exports: {} }; modules.set(name, module);
  const source = ts.transpileModule(fs.readFileSync(path.join(__dirname, '../src/lib', name + '.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  new Function('exports', 'module', 'require', source)(module.exports, module, id => load(id.replace('./', '')));
  return module.exports;
}
const { homeFeatureGroups } = load('home-feature-catalog');
const { normalizeHomeFeatureOrder, moveHomeFeature, orderedHomeFeatureGroups } = load('home-feature-order');
const defaults = normalizeHomeFeatureOrder(null), before = structuredClone(defaults);
const moved = moveHomeFeature(defaults, 'create-habit', -1);
assert.deepEqual(orderedHomeFeatureGroups(moved)[0].items.map(item => item.key), ['create', 'create-habit', 'memos', 'create-domain', 'pomodoro']);
assert.deepEqual(orderedHomeFeatureGroups(moved)[1], homeFeatureGroups[1]);
assert.deepEqual(defaults, before, 'Moving never mutates the saved order');
assert.equal(moveHomeFeature(defaults, 'create', -1), defaults);
assert.equal(moveHomeFeature(defaults, 'pomodoro', 1), defaults, 'Actions never cross into page entries');
assert.equal(moveHomeFeature(defaults, 'posts', 1), defaults);
assert.deepEqual(moveHomeFeature(moved, 'create-habit', 1), defaults);
const normalized = normalizeHomeFeatureOrder({ version: 1, keys: ['growth', 'eat', 'growth', 'posts', 'domains', 'bad', 'pomodoro', 'create'] });
assert.equal(new Set(normalized.keys).size, defaults.keys.length);
assert.deepEqual(normalized.keys.slice(0, 5), ['pomodoro', 'create', 'memos', 'create-habit', 'create-domain']);
assert.equal(normalized.keys[5], 'growth');
assert.ok(!normalized.keys.includes('eat'), 'Retired food entries are discarded without changing the other saved positions');
assert.equal(defaults.keys.length, 16);
const legacy = { version: 1, keys: ['journal', 'choose', 'growth', 'favorites', 'todos', 'categories', 'memos', 'create'] };
const savedLegacy = JSON.stringify(legacy), regrouped = normalizeHomeFeatureOrder(legacy);
const regroupedGroups = orderedHomeFeatureGroups(regrouped);
assert.deepEqual(regroupedGroups.map(group => group.title), ['快捷操作', '功能界面', '阅读与空间']);
assert.deepEqual(regroupedGroups.map(group => group.items.length), [5, 8, 3]);
assert.deepEqual(regroupedGroups[1].items.slice(0, 3).map(item => item.key), ['choose', 'growth', 'todos'], 'Existing function-page order survives the group split');
assert.deepEqual(regroupedGroups[2].items.map(item => item.key), ['journal', 'favorites', 'categories'], 'Moved entries retain their previous relative order');
assert.equal(JSON.stringify(legacy), savedLegacy, 'Regrouping never mutates the device preference on read');
assert.equal(moveHomeFeature(regrouped, 'categories', 1), regrouped, 'The new group cannot move beyond its last item');
assert.equal(moveHomeFeature(defaults, 'choose', 1), defaults, 'Function pages cannot move into the new reading group');
assert.equal(moveHomeFeature(defaults, 'categories', -1), defaults, 'Reading entries cannot move into function pages');
const readingMoved = moveHomeFeature(regrouped, 'favorites', -1);
assert.deepEqual(orderedHomeFeatureGroups(readingMoved).slice(0, 2), regroupedGroups.slice(0, 2), 'A reading-group move leaves both other groups unchanged');
assert.deepEqual(orderedHomeFeatureGroups(readingMoved)[2].items.map(item => item.key), ['favorites', 'journal', 'categories']);
assert.deepEqual(normalizeHomeFeatureOrder(JSON.parse(JSON.stringify(readingMoved))), readingMoved, 'An explicitly saved new group order survives reload');
assert.deepEqual(normalizeHomeFeatureOrder(normalized), normalized);
assert.deepEqual(normalizeHomeFeatureOrder({ version: 2, keys: ['growth'] }), defaults);
assert.deepEqual(normalizeHomeFeatureOrder({ version: 1, keys: false }), defaults);
console.log('PASS home directory ordering: immutable adjacent moves, group boundaries, rejected stale/duplicate keys and new-entry completion.');

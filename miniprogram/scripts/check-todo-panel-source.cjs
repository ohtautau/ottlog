const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const cache = new Map();
function load(name) {
  if (cache.has(name)) return cache.get(name);
  const source = fs.readFileSync(path.resolve(__dirname, '../src/lib', name + '.ts'), 'utf8');
  const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const module = { exports: {} }; cache.set(name, module.exports);
  new Function('exports', 'module', 'require', output)(module.exports, module, next => load(next.replace(/^\.\//, '')));
  return module.exports;
}
const records = load('tool-records'), { createTodo } = load('todo-data'), panel = load('todo-panel-source');
const category = load('todo-categories'), { undoTodoOperation } = load('todo-undo'), { autoSaveTodo } = load('todo-autosave');
const now = new Date(2026, 10, 3, 9);
const a = { ...createTodo('do', now), id:'a', title:'原有任务', categoryId:'legacy', tags:['工作','娱乐'], primaryTag:'旧主要标签' };
const b = { ...createTodo('delegate', now), id:'b', title:'娱乐任务', categoryId:'leisure', tags:['工作'] };
const state = { version:1, tasks:[a,b], categories:[{id:'legacy',name:'历史分类',color:'#fff'}, {id:'leisure',name:'娱乐',iconId:'game',color:'#b9dbca'}], tagStyles:{娱乐:{iconId:'game'}} };
const original = JSON.stringify(state);
assert.equal(records.isTodoState(state), true);
assert.deepEqual(category.todoCategoryChoices(records.initialTodoState).map(item=>item.name),['收集箱','娱乐','购物']);
assert.equal(category.todoCategory(state,a).name, '历史分类');
assert.equal(category.todoCategory(state,{categoryId:'missing'}).id, '');
assert.equal(panel.todoMatchesPanel(a,{kind:'category',categoryId:'leisure'}),false,'Ordinary tags never assign categories');
assert.equal(panel.todoMatchesPanel(b,{kind:'category',categoryId:'leisure'}),true);
const oldPanels={...state,panelSources:{later:{kind:'tag',tag:'工作'}}};
assert.deepEqual(panel.getTodoPanelSource(oldPanels,'later'),{kind:'quadrant',quadrantId:'later'});
assert.equal(oldPanels.panelSources.later.kind,'tag','Reading old primary-tag metadata never writes or migrates it');
let configured=panel.setTodoPanelSource(state,'later',{kind:'category',categoryId:'leisure'});
configured=panel.setTodoPanelSource(configured,'plan',{kind:'quadrant',quadrantId:'do'});
assert.equal(panel.todoPanelPresentation(configured,'later').title,'娱乐');
assert.deepEqual(configured.tasks,state.tasks);
assert.throws(()=>panel.setTodoPanelSource(state,'later',{kind:'category',categoryId:'missing'}),/有效/);
assert.throws(()=>panel.setTodoPanelSource(state,'later',{kind:'tag',tag:'娱乐'}),/有效/);
const moved=panel.moveTodoToPanel(configured,'a','later',null,['a','b']), movedA=moved.tasks.find(t=>t.id==='a');
assert.equal(movedA.categoryId,'leisure'); assert.deepEqual(movedA.tags,a.tags); assert.equal(movedA.primaryTag,a.primaryTag);
assert.equal(movedA.important,a.important); assert.equal(movedA.urgent,a.urgent);
assert.deepEqual(undoTodoOperation(moved,configured,moved),configured);
const changed={...configured,tasks:configured.tasks.map(t=>t.id==='a'?{...t,description:'远端备注',tags:['新标签'],important:false,urgent:false}:t)};
const retry=panel.retryTodoPanelMove(changed,moved,'a','later').tasks.find(t=>t.id==='a');
assert.equal(retry.categoryId,'leisure'); assert.equal(retry.description,'远端备注'); assert.deepEqual(retry.tags,['新标签']); assert.equal(retry.important,false);
assert.throws(()=>panel.retryTodoPanelMove({...changed,categories:[]},moved,'a','later'),/分类已不存在/);
assert.throws(()=>panel.retryTodoPanelMove({...changed,tasks:[b]},moved,'a','later'),/任务已不存在/);
const renamed=category.saveTodoCategory(moved,{id:'leisure',name:'娱乐休闲',iconId:'gift',existing:true});
assert.equal(renamed.categories.find(c=>c.id==='leisure').iconId,'gift');
assert.equal(panel.todoPanelPresentation(renamed,'later').title,'娱乐休闲');
assert.deepEqual(renamed.tasks,moved.tasks); assert.deepEqual(renamed.panelSources,moved.panelSources);
assert.equal(category.saveTodoCategory(renamed,{id:'leisure',name:'娱乐休闲',iconId:'gift',existing:true}),renamed);
const created=category.saveTodoCategory(state,{id:'new-stable-id',name:'项目 A',iconId:'notes'});
assert.equal(category.saveTodoCategory(created,{id:'new-stable-id',name:'项目 A',iconId:'notes'}),created,'Retry keeps stable category ID');
assert.throws(()=>category.saveTodoCategory(created,{id:'other',name:'项目 A',iconId:'notes'}),/同名/);
assert.throws(()=>category.saveTodoCategory(created,{id:'gone',name:'不恢复已删除分类',iconId:'notes',existing:true}),/移除/);
assert.throws(()=>category.saveTodoCategory(state,{id:'x',name:'收集箱',iconId:'notes'}),/同名/);
const deleted=category.deleteTodoCategory(renamed,'leisure');
assert.equal(deleted.tasks.length,2); assert.equal(deleted.tasks.find(t=>t.id==='a').categoryId,'');
assert.deepEqual(deleted.tasks.find(t=>t.id==='a').tags,a.tags); assert.equal(deleted.panelSources.later,undefined);
assert.deepEqual(undoTodoOperation(deleted,renamed,deleted),renamed,'Category deletion and task assignment undo together');
assert.equal(category.deleteTodoCategory(deleted,'leisure'),deleted);
assert.throws(()=>category.deleteTodoCategory(state,''),/不能删除/);
const inbox=panel.setTodoPanelSource(deleted,'later',{kind:'category',categoryId:''});
assert.equal(panel.todoPanelPresentation(inbox,'later').title,'收集箱');
assert.equal(panel.todoMatchesPanel(deleted.tasks[0],inbox.panelSources.later),true);
const saved=autoSaveTodo(renamed,movedA,{...movedA,title:'新标题'},movedA.tags.join(','));
assert.equal(saved.tasks.find(t=>t.id==='a').categoryId,'leisure','Autosave never folds a category into tags');
assert.equal(JSON.stringify(state),original,'Inputs and unrelated metadata remain untouched');
console.log('PASS independent categories: stable IDs, tags untouched, inbox, rename/icon/delete, panel remap, drag/undo/retry, deleted-target guards and archive compatibility.');

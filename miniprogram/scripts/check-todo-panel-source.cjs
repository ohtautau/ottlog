const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const cache = new Map();
function load(name) {
  if (cache.has(name)) return cache.get(name);
  const source = fs.readFileSync(path.resolve(__dirname, '../src/lib', name + '.ts'), 'utf8');
  const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const module = { exports: {} }; cache.set(name, module.exports);
  new Function('exports', 'module', 'require', output)(module.exports, module, next => load(next.replace(/^\.\//, '')));
  return module.exports;
}
const records = load('tool-records'), { createTodo } = load('todo-data'), panel = load('todo-panel-source');
const { undoTodoOperation } = load('todo-undo');
const now = new Date(2026, 10, 3, 9);
const a = { ...createTodo('do', now), id: 'a', title: '保留工作', tags: ['工作', '娱乐'], categoryId: 'legacy-list' };
const b = { ...createTodo('delegate', now), id: 'b', title: '休闲任务', tags: ['娱乐'] };
const state = { version: 1, categories: [{ id: 'legacy-list', name: '历史分类', color: '#fff' }], tasks: [a, b] };
const original = JSON.stringify(state);
assert.equal(records.isTodoState(state), true);
assert.equal(panel.todoPrimaryTag(a), '工作', 'Older archives derive primary from the first tag without writing');
assert.equal(panel.todoPrimaryTag({ ...a, primaryTag: '' }), '', 'Explicitly unselected primary does not fall back');
for (const slot of records.todoQuadrants) assert.deepEqual(panel.getTodoPanelSource(state, slot.id), { kind: 'quadrant', quadrantId: slot.id });
assert.equal(panel.todoMatchesPanel(a, { kind: 'tag', tag: '娱乐' }), false, 'A secondary tag does not match a primary-tag panel');
assert.equal(panel.todoMatchesPanel(b, { kind: 'tag', tag: '娱乐' }), true);
let configured = panel.setTodoPanelSource(state, 'later', { kind: 'tag', tag: '娱乐' });
configured = panel.setTodoPanelSource(configured, 'plan', { kind: 'quadrant', quadrantId: 'do' });
assert.equal(panel.todoPanelPresentation(configured, 'later').title, '娱乐');
assert.equal(panel.todoPanelPresentation(configured, 'plan').title, records.todoQuadrants[0].title);
assert.deepEqual(configured.tasks, state.tasks, 'Remapping displays never changes tasks');
assert.equal(JSON.stringify(state), original, 'Viewing and configuring never mutates the caller archive');
assert.throws(() => panel.setTodoPanelSource(state, 'later', { kind: 'tag', tag: ' ' }), /有效/);
const moved = panel.moveTodoToPanel(configured, 'a', 'later', null, ['a', 'b']);
const movedA = moved.tasks.find(task => task.id === 'a');
assert.equal(panel.todoPrimaryTag(movedA), '娱乐');
assert.deepEqual(movedA.tags, ['工作', '娱乐']);
assert.equal(movedA.categoryId, 'legacy-list');
assert.equal(movedA.important, true); assert.equal(movedA.urgent, true);
assert.deepEqual(moved.tasks.find(task => task.id === 'b'), b);
assert.deepEqual(undoTodoOperation(moved, configured, moved), configured, 'Move undo restores primary metadata and order');
const changed = { ...configured, tasks: configured.tasks.map(task => task.id === 'a' ? { ...task, important: false, urgent: false, description: '远端新备注', tags: ['工作', '新标签'] } : task) };
const retry = panel.retryTodoPanelMove(changed, moved, 'a', 'later').tasks.find(task => task.id === 'a');
assert.equal(retry.important, false); assert.equal(retry.urgent, false); assert.equal(retry.description, '远端新备注');
assert.deepEqual(retry.tags, ['工作', '新标签', '娱乐']); assert.equal(panel.todoPrimaryTag(retry), '娱乐');
assert.throws(() => panel.retryTodoPanelMove({ ...changed, tasks: [b] }, moved, 'a', 'later'), /不存在/);
const tagged = panel.saveTodoTag(moved, { originalName: '娱乐', name: '娱乐休闲', iconId: 'game' });
assert.equal(tagged.tagStyles['娱乐休闲'].iconId, 'game');
assert.equal(panel.todoPrimaryTag(tagged.tasks.find(task => task.id === 'a')), '娱乐休闲');
assert.deepEqual(tagged.panelSources.later, { kind: 'tag', tag: '娱乐休闲' });
assert.deepEqual(tagged.tasks.find(task => task.id === 'a').tags, ['工作', '娱乐休闲']);
assert.equal(tagged.tasks.find(task => task.id === 'a').categoryId, 'legacy-list');
assert.equal(panel.saveTodoTag(tagged, { originalName: '娱乐', name: '娱乐休闲', iconId: 'game' }), tagged, 'Uncertain rename retries are idempotent');
const created = panel.saveTodoTag(state, { name: '摄影', iconId: 'camera' });
assert.equal(panel.saveTodoTag(created, { name: '摄影', iconId: 'camera' }), created, 'Uncertain create retries are idempotent');
assert.throws(() => panel.saveTodoTag(created, { name: '摄影', iconId: 'gift' }), /同名/);
assert.throws(() => panel.saveTodoTag(state, { originalName: '工作', name: '娱乐', iconId: 'game' }), /同名/);
for (const name of ['', '工作 娱乐', '工作，娱乐', 'A'.repeat(33)]) assert.throws(() => panel.saveTodoTag(state, { name, iconId: 'notes' }), /标签/);
const deleted = panel.deleteTodoTag(tagged, '娱乐休闲');
assert.equal(deleted.tagStyles['娱乐休闲'], undefined); assert.equal(deleted.panelSources.later, undefined);
assert.equal(deleted.tasks.length, 2); assert.deepEqual(deleted.tasks.find(task => task.id === 'a').tags, ['工作']);
assert.equal(panel.todoPrimaryTag(deleted.tasks.find(task => task.id === 'a')), '');
assert.deepEqual(deleted.categories, state.categories, 'Legacy category archives are not migrated or deleted');
assert.equal(records.isTodoState(tagged), true);
console.log('PASS task panel sources: legacy/explicit primary, secondary exclusion, display-only remap, tag drag/undo/retry, rename/create idempotency, deletion and legacy archive preservation.');

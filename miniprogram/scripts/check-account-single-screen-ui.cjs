const path = require('node:path');
module.exports = async ({ page, origin, out, width, expect }) => {
  await page.goto(`${origin}/?account-single-screen=${width}#/pages/index/index`);
  await expect(page.locator('.preview-native-tabs a')).toHaveText(['今日', '待办', '专注', '领域', '习惯'].map((text, i) => ['⌂','☑','◷','◇','✿'][i] + text));
  const open = page.getByRole('button', { name: /^打开账号窗口/ });
  const dialog = page.getByRole('dialog', { name: '账号', exact: true });
  await expect(open).toHaveAttribute('aria-label', /未登录/);
  await expect(open.locator('.account-symbol')).not.toHaveClass(/is-authenticated/);
  await open.click(); await expect(dialog.getByLabel('账号名称')).toBeVisible();
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0);
  await open.click(); await dialog.getByLabel('账号名称').fill('cancelled-input');
  await dialog.getByRole('button', { name: '关闭账号窗口', exact: true }).click();
  await open.click(); await expect(dialog.getByLabel('账号名称')).toHaveValue('');
  expect(await page.evaluate(() => window.__miniRequests.filter(request => request.method === 'POST' && /\/account\/(login|register)/.test(request.path)))).toEqual([]);
  await dialog.getByRole('button', { name: '创建账号', exact: true }).click();
  await dialog.getByLabel('账号名称').fill('preview-reader');
  await dialog.getByLabel('账号密码').fill('short');
  await expect(dialog.getByRole('button', { name: '注册并登录', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: '登录', exact: true }).click();
  await dialog.getByLabel('账号密码').fill('fixture-only-password');
  const remember = dialog.getByRole('button', { name: '记住登录状态（30 天）', exact: true });
  await expect(remember).toHaveAttribute('aria-pressed', 'false');
  await remember.click(); await expect(remember).toHaveAttribute('aria-pressed', 'true');
  await expect(dialog.getByRole('button', { name: '登录并同步', exact: true })).toBeInViewport();
  await dialog.getByRole('button', { name: '登录并同步', exact: true }).click();
  await expect(dialog.locator('.account-window-name')).toHaveText('preview-reader');
  expect(await page.evaluate(() => window.__miniRequests.filter(request => request.path === '/account/login').at(-1)?.data.rememberMe)).toBe(true);
  await expect(dialog).toContainText('读者账号');
  await expect(open).toHaveAttribute('aria-label', /已登录：preview-reader/);
  await expect(open.locator('.account-symbol')).toHaveClass(/is-authenticated/);
  expect(await dialog.locator('.sheet-actions').evaluate(node => getComputedStyle(node).paddingBottom)).toBe('16px');
  expect(await page.evaluate(() => window.__miniRequests.filter(request => request.path.startsWith('/favorites')))).toEqual([]);
  await page.screenshot({ path: path.join(out, `account-window-signed-${width}.png`) });
  await dialog.getByRole('button', { name: '退出登录', exact: true }).click();
  await expect(dialog.getByLabel('账号密码')).toHaveValue('');
  await expect(remember).toHaveAttribute('aria-pressed', 'false');
  await expect(open).toHaveAttribute('aria-label', /未登录/);
  await expect(open.locator('.account-symbol')).not.toHaveClass(/is-authenticated/);
  await expect(dialog.getByRole('button', { name: '登录并同步', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: '关闭账号窗口', exact: true }).click();
  await page.locator('.preview-native-tabs a[href="#/pages/pomodoro/index"]').click();
  await expect(page.locator('.focus-page')).toBeVisible();
  await expect(page.locator('.preview-native-tabs .active')).toContainText('专注');
  await page.locator('.preview-native-tabs a[href="#/pages/index/index"]').click();
  await page.getByRole('button', { name: '打开番茄钟', exact: true }).click();
  await expect(page.locator('.focus-page')).toBeVisible();
  await expect.poll(() => page.locator('.focus-timer-stage').evaluate(node => node.querySelector('.focus-tomato-scene').getBoundingClientRect().height - node.getBoundingClientRect().height)).toBeLessThanOrEqual(1);
  await page.screenshot({ path: path.join(out, `focus-tab-${width}.png`) });
  await page.getByRole('button', { name: '开始专注', exact: true }).click();
  await page.getByRole('button', { name: '暂停', exact: true }).click();
  await expect(page.getByRole('button', { name: '继续', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '继续', exact: true }).click();
  await page.getByRole('button', { name: '暂停', exact: true }).click();
  await page.getByRole('button', { name: '结束', exact: true }).click();
  await expect(page.getByRole('button', { name: '开始专注', exact: true })).toBeVisible();
  await page.locator('.preview-native-tabs a[href="#/pages/index/index"]').click();
  await page.getByRole('button', { name: '操作：专注', exact: true }).click();
  await expect(page.locator('.focus-page')).toBeVisible();
  await page.getByRole('button', { name: '暂停', exact: true }).click();
  await page.getByRole('button', { name: '结束', exact: true }).click();
  await page.evaluate(() => { location.hash = '#/pages/favorites/index'; });
  await expect(page.getByRole('button', { name: '登录查看收藏', exact: true })).toBeVisible();
  await expect(page.locator('#page-more,.account-links,.account-data-notice')).toHaveCount(0);
  await page.getByRole('button', { name: '登录查看收藏', exact: true }).click();
  await expect(dialog.getByLabel('账号名称')).toBeVisible();
  await page.screenshot({ path: path.join(out, `account-window-guest-${width}.png`) });
  await dialog.getByLabel('账号名称').fill('retained-draft');
  await dialog.getByLabel('账号密码').fill('fixture-only-password');
  const writes = await page.evaluate(() => window.__miniRequests.filter(request => request.method === 'POST' && request.path === '/account/login').length);
  await page.evaluate(() => { window.__miniFixture.sessionProfile = { authenticated: true, userName: 'another-owner', isAdmin: false }; });
  await dialog.getByRole('button', { name: '登录并同步', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('账号已切换');
  await expect(dialog.getByLabel('账号名称')).toHaveValue('retained-draft');
  expect(await page.evaluate(() => window.__miniRequests.filter(request => request.method === 'POST' && request.path === '/account/login').length)).toBe(writes);
};

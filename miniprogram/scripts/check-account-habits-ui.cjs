const path = require('node:path');
module.exports = async ({ page, origin, out, width, expect }) => {
  const guestKey = 'ottlog-mini-tool-v1:guest:reminders';
  const guest = { data: { version: 1, items: [{ id: 'old-guest-habit', title: '游客旧习惯不应显示', group: '生活', kind: 'notes', note: '', minutes: 0, enabled: true }], done: { '2026-10-29': ['old-guest-habit'] } }, pending: false, revision: 3 };
  await page.addInitScript(({ guestKey, guest }) => localStorage.setItem(guestKey, JSON.stringify(guest)), { guestKey, guest });
  await page.goto(`${origin}/?account-habits=${width}#/pages/daily/index`);
  await expect(page.locator('.empty-state.is-habits')).toBeVisible();
  await expect(page.locator('.daily-page')).not.toContainText('游客旧习惯不应显示');
  await expect(page.getByRole('button', { name: '排序习惯', exact: true })).toBeDisabled();
  await expect(page.locator('.empty-state.is-habits button')).toHaveCount(0);
  await expect(page.locator('.daily-suggestion')).toHaveCount(0);
  await expect(page.locator('.habit-editor,.daily-detail-sheet,.daily-reflection-sheet')).toHaveCount(0);
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)), guestKey)).toEqual(guest);
  const account = { version: 1, items: [{ id: 'account-only', title: '账号A的专属习惯', group: '未分类', kind: 'notes', note: '保留备注', minutes: 0, enabled: true, timePeriod: 'free' }], done: {} };
  await page.evaluate(account => {
    window.__miniFixture.sessionProfile = { authenticated: true, userName: 'habits-a', isAdmin: false };
    window.__miniFixture.accountToolStates = { 'habits-a': { reminders: account }, 'habits-b': {} };
    window.__miniPreviewControl.emit('ottlog-session');
  }, account);
  await expect(page.locator('.daily-page')).toContainText('账号A的专属习惯');
  await expect(page.locator('.empty-state.is-habits')).toHaveCount(0);
  await expect(page.locator('.tool-status')).toHaveCount(0);
  await page.evaluate(() => { window.__miniFixture.sessionProfile = { authenticated: true, userName: 'habits-b', isAdmin: false }; window.__miniPreviewControl.emit('ottlog-session'); });
  await expect(page.locator('.empty-state.is-habits')).toBeVisible();
  await expect(page.locator('.daily-page')).not.toContainText('账号A的专属习惯');
  await expect(page.locator('.daily-page')).not.toContainText('力量训练');
  await page.evaluate(() => { window.__miniFixture.sessionProfile = { authenticated: true, userName: 'habits-a', isAdmin: false }; window.__miniPreviewControl.emit('ottlog-session'); });
  await expect(page.locator('.daily-page')).toContainText('账号A的专属习惯');
  await expect(page.locator('.tool-status')).toHaveCount(0);
  await page.evaluate(() => { window.__miniFixture.sessionProfile = { authenticated: false }; window.__miniPreviewControl.emit('ottlog-session'); });
  await expect(page.locator('.empty-state.is-habits')).toBeVisible();
  await expect(page.locator('.daily-page')).not.toContainText('账号A的专属习惯');
  expect(await page.evaluate(() => window.__miniRequests.filter(request => request.method === 'PUT' && request.path === '/personal-tools/reminders'))).toEqual([]);
  expect(await page.evaluate(() => window.__miniFixture.accountToolStates['habits-a'].reminders)).toEqual(account);
  await page.screenshot({ path: path.join(out, `guest-habits-${width}.png`) });
  await page.getByRole('button', { name: '登录创建习惯', exact: true }).click();
  await expect(page.locator('.account-window')).toBeVisible();
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)), guestKey)).toEqual(guest);
};

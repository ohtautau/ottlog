const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/lib/habit-recommendations.ts'), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const model = {}; new Function('exports', output)(model);
const { habitOpenKey, emptyHabitOpenLog, cleanHabitOpenLog, recordHabitOpening, typicalOpeningMinute, clockDistance, suggestHabits } = model;
const at = (day, hour, minute = 0) => new Date(2026, 8, day, hour, minute).getTime();
const item = (id, enabled = true) => ({ id, title: id, note: '', kind: 'plant', group: '精神', minutes: 0, enabled });
const now = at(15, 0, 5);
assert.notEqual(habitOpenKey('guest'), habitOpenKey('reader:a'));
assert.notEqual(habitOpenKey('reader:a/b'), habitOpenKey('reader:a%2Fb'));
assert.equal(typicalOpeningMinute([at(10, 8), at(11, 8)]), null, 'Two days cannot establish a routine');
assert.equal(typicalOpeningMinute([at(10, 8), at(10, 8, 1), at(10, 8, 2)]), null, 'Repeated openings on one day cannot create a routine');
assert.equal(clockDistance(1430, 10), 20);
assert.ok(clockDistance(typicalOpeningMinute([at(9, 23, 50), at(10, 0, 10), at(11, 0), at(12, 12)]), 0) <= 1, 'Noon outlier does not pull a midnight routine towards noon');
assert.equal(typicalOpeningMinute([at(7, 6), at(8, 8), at(9, 8), at(10, 8), at(11, 8), at(12, 18)]), 480, 'Outliers and extremes do not skew usual morning time');
let log = recordHabitOpening(emptyHabitOpenLog(), 'night', at(10, 23, 50));
assert.equal(recordHabitOpening(log, 'night', at(10, 23, 55)), log, 'Only the first deliberate opening of a local day is sampled');
log = recordHabitOpening(log, 'night', at(11, 0, 10));
assert.equal(log.opened.night.length, 2, 'Local midnight starts a new sample day');
const malformed = { version: 1, opened: { night: [at(14, 23), at(14, 22), now + 1, NaN, 'bad', now - 181 * 86400000], removed: [at(14, 8)] } };
assert.deepEqual(cleanHabitOpenLog(malformed, ['night'], now).opened, { night: [at(14, 22)] }, 'Expired/future/duplicate and deleted habit data is ignored');
assert.deepEqual(cleanHabitOpenLog(null, ['night'], now), emptyHabitOpenLog());
const ids = ['old1', 'old2', 'old3', 'night', 'morning', 'new', 'paused', 'done'];
const state = { version: 1, items: ids.map(id => item(id, id !== 'paused')), done: { '2026-09-01': ['old1', 'old2', 'old3'], '2026-09-15': ['done'] } };
log = { version: 1, opened: { night: [at(11, 0), at(12, 0, 10), at(13, 23, 50)], morning: [at(11, 8), at(12, 8, 10), at(13, 7, 50)], paused: [at(11, 0), at(12, 0), at(13, 0)], done: [at(11, 0), at(12, 0), at(13, 0)] } };
const recommended = suggestHabits(state, log, now, 42);
assert.deepEqual(recommended.timely.map(row => row.item.id), ['night', 'morning'], 'Closest robust average opening time sorts first across midnight');
assert.equal(recommended.learned, true);
assert.equal(recommended.randomPoolCount, 4);
assert.equal(recommended.random.length, 4, 'The random section can fill more than one row');
assert.deepEqual(suggestHabits(state, log, now, 42), recommended, 'Random selection remains stable within the same entry');
const varied = new Set(Array.from({ length: 20 }, (_, seed) => suggestHabits(state, log, now, seed, { randomCount: 2 }).random.map(row => row.item.id).join(',')));
assert.ok(varied.size > 1, 'Refresh can return a different random subset');
assert.equal(new Set([...recommended.random, ...recommended.timely].map(row => row.item.id)).size, 6, 'No duplicate cards across sections');
assert.ok([...recommended.timely, ...recommended.random].every(row => row.item.enabled && !state.done['2026-09-15'].includes(row.item.id)), 'Paused and already completed habits stay outside both sections');
const cold = suggestHabits({ ...state, done: {} }, emptyHabitOpenLog(), now, 42);
assert.equal(cold.learned, false);
assert.equal(cold.timely.length, 4, 'Cold start still fills the first section');
assert.ok(cold.timely.every(row => row.typicalMinute === undefined), 'Check-in dates never fabricate opening times');
assert.deepEqual(suggestHabits({ ...state, done: {} }, emptyHabitOpenLog(), now, 77).timely, cold.timely, 'Random refresh keeps cold-start first-section cards steady');
const manyState = { version: 1, items: ['night', 'morning', ...Array.from({ length: 14 }, (_, i) => `random-${i}`)].map(id => item(id)), done: {} };
const before = JSON.stringify({ state: manyState, log });
const first = suggestHabits(manyState, log, now, 7, { timelyCount: 2, randomCount: 6 });
const excluded = first.random.map(row => row.item.id);
const second = suggestHabits(manyState, log, now, 8, { timelyCount: 2, randomCount: 6, excludeRandomIds: excluded });
assert.equal(second.random.length, 6);
assert.ok(second.random.every(row => !excluded.includes(row.item.id)), 'A refresh replaces every card when enough other habits exist');
assert.deepEqual(second.timely, first.timely, 'Random refresh never reorders time-based suggestions');
assert.deepEqual(excluded, first.random.map(row => row.item.id), 'The caller-owned exclusion array stays intact');
assert.equal(JSON.stringify({ state: manyState, log }), before, 'Ranking and shuffling do not mutate state or opening logs');
const shortState = { ...manyState, items: manyState.items.slice(0, 7) };
const shortFirst = suggestHabits(shortState, log, now, 10, { timelyCount: 2, randomCount: 4 });
const shortExcluded = shortFirst.random.map(row => row.item.id);
const shortNext = suggestHabits(shortState, log, now, 11, { timelyCount: 2, randomCount: 4, excludeRandomIds: shortExcluded });
assert.equal(shortNext.random.length, 4, 'A small pool still fills the requested number of cards');
assert.equal(shortNext.random.filter(row => !shortExcluded.includes(row.item.id)).length, 1, 'Refresh includes the sole alternative instead of returning the identical set');
const exhausted = suggestHabits(shortState, log, now, 12, { timelyCount: 2, randomCount: 20, excludeRandomIds: shortExcluded });
assert.equal(exhausted.random.length, exhausted.randomPoolCount, 'Pool count lets the UI disable refresh when no alternative exists');
const counts = suggestHabits(manyState, log, now, 1, { timelyCount: 1, randomCount: 8 });
assert.equal(counts.timely.length, 1);
assert.equal(counts.random.length, 8, 'The caller can distribute extra rows to the random section');
const noTimely = suggestHabits(manyState, log, now, 1, { timelyCount: 0, randomCount: 3 });
assert.equal(noTimely.timely.length, 0);
assert.equal(noTimely.random.length, 3);
const noCards = suggestHabits(manyState, log, now, 1, { timelyCount: -1, randomCount: -2 });
assert.deepEqual(noCards.timely, []);
assert.deepEqual(noCards.random, []);
const allDone = { ...manyState, done: { '2026-09-15': manyState.items.map(row => row.id) } };
assert.deepEqual(suggestHabits(allDone, log, now, 1), { timely: [], random: [], learned: false, randomPoolCount: 0 }, 'Completing all habits produces a clear empty state');
const hostile = JSON.parse('{"version":1,"opened":{"__proto__":[]}}');
const hostileState = { version: 1, items: [item('__proto__')], done: {} };
assert.doesNotThrow(() => suggestHabits(hostileState, cleanHabitOpenLog(hostile, ['__proto__'], now), now, 1));
console.log('PASS habit recommendations: owner keys, robust circular opening time, stable cold start, configurable two-section counts, whole-group refresh, small-pool replacement and exclusions.');

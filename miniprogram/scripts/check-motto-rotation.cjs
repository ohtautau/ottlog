const path = require('node:path');
module.exports = async function ({ page, origin, out, width, expect }) {
  const trigger = () => page.getByRole('button', { name: '格言轮播设置', exact: true });
  const panel = () => page.getByRole('dialog', { name: '格言轮播设置', exact: true });
  const input = () => panel().getByRole('spinbutton', { name: '格言轮播间隔', exact: true });
  const prompt = () => page.getByRole('dialog', { name: '保存修改？', exact: true });
  const save = () => panel().getByRole('button', { name: '保存', exact: true });
  const storage = () => page.evaluate(() => window.__miniPreviewControl.readStorage('ottlog-mini-tool-v1:guest:mottos').data);
  const original = (await storage()).mottos;
  const settingsBox = await trigger().boundingBox(), createBox = await page.locator('.mottos-heading .page-toolbar-create').boundingBox();
  expect(settingsBox.x + settingsBox.width).toBeLessThanOrEqual(createBox.x);
  expect(settingsBox.y + settingsBox.height / 2).toBeCloseTo(createBox.y + createBox.height / 2, 0);
  expect(settingsBox.width).toBeGreaterThanOrEqual(40); expect(settingsBox.height).toBeGreaterThanOrEqual(40);
  await trigger().click(); await expect(input()).toHaveValue('15'); await expect(input()).not.toBeFocused();
  await expect(panel().getByRole('button', { name: '取消', exact: true })).toHaveCount(0);
  const saveLayout = await save().evaluate(node => {
    const button = node.getBoundingClientRect(), actions = node.parentElement.getBoundingClientRect(), style = getComputedStyle(node.parentElement);
    return { buttonWidth: button.width, availableWidth: actions.width - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight), height: button.height, buttons: node.parentElement.querySelectorAll('button').length };
  });
  expect(saveLayout.buttons).toBe(1); expect(saveLayout.buttonWidth).toBeCloseTo(saveLayout.availableWidth, 0); expect(saveLayout.height).toBeGreaterThanOrEqual(40);
  const actions = await panel().locator('.mottos-rotation-actions').boundingBox();
  await input().fill('0'); await save().click(); await expect(panel().getByRole('alert')).toContainText('整数秒数');
  await expect(input()).toHaveValue('0'); expect((await panel().locator('.mottos-rotation-actions').boundingBox()).y).toBeCloseTo(actions.y, 0);
  await input().fill('8'); await panel().getByRole('button', { name: '关闭轮播设置', exact: true }).click();
  await expect(prompt()).toBeVisible(); await prompt().getByRole('button', { name: '继续编辑', exact: true }).click();
  await expect(input()).toHaveValue('8'); await panel().getByRole('button', { name: '关闭轮播设置', exact: true }).click();
  await prompt().getByRole('button', { name: '不保存', exact: true }).click();
  expect((await storage()).rotationSeconds).toBeUndefined();
  await trigger().click(); await input().fill('9'); await page.locator('.form-popover-backdrop').click({ position: { x: 2, y: 2 } });
  await expect(prompt()).toBeVisible(); await prompt().getByRole('button', { name: '不保存', exact: true }).click();
  await expect(panel()).toHaveCount(0); expect((await storage()).rotationSeconds).toBeUndefined();
  await trigger().click(); await input().fill('3'); await save().click(); await expect(panel()).toHaveCount(0);
  expect(await storage()).toEqual({ version: 1, mottos: original, rotationSeconds: 3 });
  await page.reload(); await trigger().click(); await expect(input()).toHaveValue('3');
  await page.screenshot({ path: path.join(out, `motto-rotation-${width}.png`) });
  await input().fill('4'); await page.evaluate(() => { window.__miniFixture.failToolWrites = ['mottos']; });
  await panel().getByRole('button', { name: '关闭轮播设置', exact: true }).click();
  await prompt().getByRole('button', { name: '保存', exact: true }).click(); await expect(prompt()).toHaveCount(0);
  await expect(panel().getByRole('alert')).toContainText('本机存储不可用'); await expect(input()).toHaveValue('4'); await expect(input()).toBeDisabled();
  expect((await storage()).rotationSeconds).toBe(3);
  await page.evaluate(() => { window.__miniFixture.failToolWrites = []; });
  await panel().getByRole('button', { name: '关闭轮播设置', exact: true }).click();
  await prompt().getByRole('button', { name: '保存', exact: true }).click(); await expect(panel()).toHaveCount(0);
  expect(await storage()).toEqual({ version: 1, mottos: original, rotationSeconds: 4 });
  await page.evaluate(() => { location.hash = '#/pages/index/index'; });
  const text = () => page.locator('.today-quote-text');
  await expect(page.locator('.today-quote-count')).toContainText('/61');
  await page.locator('.today-quote').dispatchEvent('touchstart', { touches: [{ identifier: 1, clientX: 100, clientY: 150 }] });
  const before = await text().textContent();
  await page.locator('.today-quote').dispatchEvent('touchend', { touches: [] });
  await page.clock.runFor(3900); await expect(text()).toHaveText(before);
  await page.clock.runFor(200); await expect(text()).not.toHaveText(before);
  await page.getByRole('button', { name: '管理格言', exact: true }).click(); await trigger().click();
  await page.evaluate(() => {
    window.__miniFixture.accountToolStates = { 'rotation-reader': { mottos: { version: 1, mottos: ['账号格言'], rotationSeconds: 22 } } };
    window.__miniFixture.sessionProfile = { authenticated: true, userName: 'rotation-reader', isAdmin: false }; window.__miniPreviewControl.emit('ottlog-session');
  });
  await expect(panel()).toHaveCount(0); await trigger().click(); await expect(input()).toHaveValue('22');
  await input().fill('23'); await save().click(); await expect(panel()).toHaveCount(0);
  expect(await page.evaluate(() => window.__miniPreviewControl.readStorage('ottlog-mini-tool-v1:reader:rotation-reader:mottos').data)).toEqual({ version: 1, mottos: ['账号格言'], rotationSeconds: 23 });
  await expect.poll(() => page.evaluate(() => window.__miniRequests.filter(request => request.path === '/personal-tools/mottos' && request.method === 'PUT').length)).toBeGreaterThan(0);
  expect((await storage()).rotationSeconds).toBe(4);
  await page.evaluate(() => { window.__miniFixture.sessionProfile = { authenticated: false, userName: null, isAdmin: false }; window.__miniPreviewControl.emit('ottlog-session'); });
  await trigger().click(); await expect(input()).toHaveValue('4'); await panel().getByRole('button', { name: '关闭轮播设置', exact: true }).click();
  await expect(prompt()).toHaveCount(0);
  expect(await page.evaluate(() => window.__miniRequests.filter(request => request.path === '/mottos' && request.method !== 'GET'))).toEqual([]);
};

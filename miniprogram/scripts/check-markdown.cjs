const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createRequire } = require('node:module');
const ts = require('typescript');
const source = path.resolve(__dirname, '../src/lib/markdown.ts');
const compiled = ts.transpileModule(fs.readFileSync(source, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS, esModuleInterop: true } }).outputText;
const moduleContext = { exports: {} };
const textExports = {}, textSource = path.resolve(__dirname, '../src/lib/text-whitespace.ts');
vm.runInNewContext(ts.transpileModule(fs.readFileSync(textSource, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } }).outputText, { exports: textExports });
vm.runInNewContext(compiled, { exports: moduleContext.exports, require: name => name === './text-whitespace' ? textExports : createRequire(source)(name) }, { filename: source });
const render = moduleContext.exports.createMarkdownRenderer(source => source.startsWith('http') ? source : `http://127.0.0.1:5229${source}`);
assert.equal(render('段落\n\n下一段\n\t \u3000\u00a0'), render('段落\n\n下一段'), 'Markdown trims only the outer trailing whitespace');

const html = render('# 标题\n\n段落 **加粗** 和 *强调* 和 `const answer = 42;`\n\n> 一段引用\n\n- 读书\n- 写字\n\n1. 开始\n2. 结束\n\n| 项目 | 数量 |\n| --- | --- |\n| 收藏 | 2 |\n\n```typescript\nif (a < 2) console.log("<script>");\n```\n\n![本地图](/images/upload.png)\n\n![外部图](https://images.unsplash.com/photo-test?w=600)');
assert.match(html, /<h1 style="[^"]*font-size:30px/);
assert.match(html, /<strong style="[^"]*font-weight:700/);
assert.match(html, /<blockquote style="[^"]*border-left:4px/);
assert.match(html, /<ul style="[^"]*padding-left:24px/);
assert.match(html, /<ol style="[^"]*padding-left:26px/);
assert.match(html, /<table style="[^"]*border-collapse:collapse/);
assert.match(html, /<td style="[^"]*border:1px/);
assert.match(html, /<pre style="[^"]*white-space:pre-wrap/);
assert.match(html, /if \(a &lt; 2\)/);
assert.match(html, /src="http:\/\/127\.0\.0\.1:5229\/images\/upload\.png"/);
assert.match(html, /src="https:\/\/images\.unsplash\.com\/photo-test\?w=600"/);
assert.match(html, /max-width:100%;height:auto/);
assert.ok(!html.includes('<script>'));
const untrusted = render('<script>alert(1)</script>\n\n[bad](javascript:alert(1))\n\n![bad](data:image/png;base64,abcd)\n\n```"><img src=x onerror=alert(1)>\n<img src=x onerror=alert(1)>\n```');
assert.ok(!untrusted.includes('<script>'));
assert.ok(!untrusted.includes('<img'));
assert.ok(!/href="javascript:|src="data:/i.test(untrusted));
assert.match(untrusted, /&lt;script&gt;/);
assert.match(render('公式源码：$x^2$'), /\$x\^2\$/);
const inherit = moduleContext.exports.createMarkdownRenderer(source => source, { inheritTypography: true });
const inherited = inherit('# 标题\n\n正文 **强调** *斜体* ~~划去~~ [链接](https://example.com) `代码`\n\n> 引用\n\n- 列表\n\n| 项目 | 数量 |\n| --- | --- |\n| 收藏 | 2 |\n\n```typescript\nconst value = "<script>";\n```');
for (const tag of ['h1', 'p', 'strong', 'em', 's', 'a', 'blockquote', 'li', 'table', 'thead', 'th', 'td', 'code', 'pre']) {
  const nodes = [...inherited.matchAll(new RegExp(`<${tag}\\b[^>]*style="([^"]*)"`, 'g'))];
  assert.ok(nodes.length, `Inherited Markdown preserves ${tag} formatting`);
  for (const node of nodes) assert.match(node[1], /font-size:inherit;color:inherit;$/, `${tag} keeps the record's font size and signed color`);
}
assert.match(inherited, /^<div style="[^"]*font-size:inherit;color:inherit;/);
const inheritedUnsafe = inherit('<script>alert(1)</script>\n\n```js\n<img src=x onerror=alert(1)>\n```');
assert.ok(!inheritedUnsafe.includes('<script>'));
assert.ok(!inheritedUnsafe.includes('<img'));
assert.match(inheritedUnsafe, /&lt;script&gt;/);
assert.ok(!/href="javascript:|src="data:/i.test(inherit('[bad](javascript:alert(1))\n\n![bad](data:image/png;base64,abcd)')));
console.log('PASS mini Markdown: default and inherited typography, rich nodes, escaped code/HTML, local and external images, unsafe image/link rejection, math source preserved.');

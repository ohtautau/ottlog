const path = require('node:path');

module.exports = async function checkUncategorizedDomain({ page, origin, out, width, expect }) {
  const key = 'ottlog-mini-tool-v1:guest:domains', habitKey = 'ottlog-mini-tool-v1:guest:reminders';
  const ids = ['growth', 'work', 'english', 'fitness', 'life', 'mind', 'photo', 'media'];
  const names = ['成长', '工作', '英语', '健身', '生活', '心理', '摄影', '自媒体'];
  const initial = { version: 1, domains: ids.map((id, index) => ({ id, name: names[index], iconId: 'plant', longTermGoal: null, shortTermGoal: null, habits: [], positiveRecords: [], negativeRecords: [] })), completedGoals: [] };
  const item = (id, title, group, domainId) => ({ id, title, group, domainId, kind: 'notes', note: '', minutes: 0, enabled: true, priority: 'none' });
  const reminders = { version: 1, items: [item('unset', '自由收纳', '未分类'), item('orphan', '原领域习惯', '原领域', 'deleted-domain'), item('work-habit', '工作计划', '工作', 'work')], done: {}, reflections: [] };
  let generation = 0;
  async function fresh(state = initial) {
    await page.goto(`${origin}/?uncategorized-${width}-${++generation}#/pages/posts/index`);
    await page.evaluate(({ state, reminders, key, habitKey }) => {
      localStorage.clear(); window.__miniFixture.persistEntryTools = true;
      window.__miniFixture.sessionProfile = { authenticated: false, userName: null, isAdmin: false };
      window.__miniFixture.guestToolStates = { domains: state, reminders };
      localStorage.setItem(key, JSON.stringify({ data: state, pending: false, revision: 9 }));
      localStorage.setItem(habitKey, JSON.stringify({ data: reminders, pending: false, revision: 6 }));
      location.hash = '#/pages/domains/index';
    }, { state, reminders, key, habitKey });
    await expect(page.locator('.domain-first-grid .domain-entry')).toHaveCount(8);
  }
  const read = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key);
  const system = () => page.locator('.domain-uncategorized-shell');
  const outer = () => page.locator('.page-scroll');
  async function secondScreen() {
    await expect(page.locator('.domain-first-grid .domain-uncategorized-shell')).toHaveCount(0);
    await expect(page.locator('.domain-continuation-grid .domain-uncategorized-shell')).toHaveCount(1);
    const position = await system().evaluate(node => ({ top: node.getBoundingClientRect().top, edge: document.querySelector('.domain-entry-scroll').getBoundingClientRect().bottom }));
    expect(position.top).toBeGreaterThanOrEqual(position.edge - 1);
    await page.locator('.domain-entry-scroll').evaluate(node => { node.scrollTop = node.scrollHeight; });
    expect(await outer().evaluate(node => node.scrollTop)).toBe(0);
    await expect(system()).toBeInViewport();
  }
  await fresh(); const original = await read();
  await secondScreen();
  await page.screenshot({ path: path.join(out, `domain-uncategorized-second-${width}.png`) });
  await system().getByRole('button', { name: '打开未分类领域', exact: true }).click();
  await expect(page.locator('.domain-name')).toHaveText('未分类');
  await expect(page.getByRole('button', { name: '编辑未分类领域', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: '删除未分类领域', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: '查看习惯：自由收纳', exact: true })).toHaveCount(1);
  await expect(page.getByRole('button', { name: '查看习惯：原领域习惯', exact: true })).toHaveCount(1);
  expect(await read(), 'Reading the empty system card does not create a persisted domain').toEqual(original);
  await page.getByRole('button', { name: '创建未分类习惯', exact: true }).click();
  const habitEditor = page.locator('.daily-editor-sheet');
  await habitEditor.locator('input').first().fill('未分类新习惯');
  await habitEditor.locator('.ui-button-primary').click();
  await expect(habitEditor).toHaveCount(0);
  expect(await read(), 'Creating a shared uncategorized habit does not seed the domain archive').toEqual(original);
  const savedHabit = await page.evaluate(key => JSON.parse(localStorage.getItem(key)).data.items.find(item => item.title === '未分类新习惯'), habitKey);
  expect(savedHabit.group).toBe('未分类'); expect(savedHabit.domainId).toBeUndefined();
  await page.getByRole('button', { name: '创建记录', exact: true }).click();
  await expect(page.getByRole('button', { name: '选择记录领域', exact: true })).toHaveText('未分类');
  await page.locator('.entry-composer .progress-record-field').first().locator('textarea').fill('未分类记录保留在这里');
  await page.getByRole('button', { name: '保存记录', exact: true }).click();
  await expect(page.locator('.entry-composer')).toHaveCount(0);
  const stored = (await read()).data, savedDomain = stored.domains.find(domain => domain.name === '未分类');
  expect(stored.domains).toHaveLength(9); expect(savedDomain.positiveRecords[0].content).toBe('未分类记录保留在这里');
  await expect(page.locator('.domain-record-content')).toContainText(['未分类记录保留在这里']);
  await page.getByRole('button', { name: '设置未分类短期目标', exact: true }).click();
  await page.getByRole('textbox', { name: '目标内容', exact: true }).fill('整理未分类内容');
  await page.getByRole('button', { name: '创建目标', exact: true }).click();
  await expect(page.locator('.domain-sheet-goal')).toHaveCount(0);
  expect((await read()).data.domains.find(domain => domain.id === savedDomain.id).shortTermGoal.content).toBe('整理未分类内容');
  await page.getByRole('button', { name: '返回领域列表', exact: true }).click();
  await secondScreen();
  await expect(system()).toHaveAttribute('id', `domain-entry-${savedDomain.id}`);
  await page.getByRole('button', { name: '排序领域', exact: true }).click();
  await expect(system().locator('.card-move-actions,.domain-entry-actions')).toHaveCount(0);
  await page.reload(); await secondScreen();
  await expect(system().locator('.domain-progress-card-goal')).toContainText('整理未分类内容');

  const legacy = structuredClone(initial);
  legacy.domains.unshift({ ...savedDomain, id: 'legacy-uncategorized', shortTermGoal: null });
  await fresh(legacy); const legacyBytes = await read();
  await secondScreen(); await system().getByRole('button', { name: '打开未分类领域', exact: true }).click();
  await expect(page.locator('.domain-record-content')).toContainText(['未分类记录保留在这里']);
  expect(await read(), 'A legacy uncategorized domain keeps its original ID, slot and records').toEqual(legacyBytes);
  await page.getByRole('button', { name: '返回领域列表', exact: true }).click();
  await page.getByRole('button', { name: '排序领域', exact: true }).click();
  await expect(page.getByRole('button', { name: '上移成长领域', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: '下移自媒体领域', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '下移成长领域', exact: true }).click();
  await expect.poll(async () => (await read()).data.domains[1].id).toBe('work');
  expect((await read()).data.domains[0], 'Sorting ordinary cards preserves the legacy system slot and complete record').toEqual(legacyBytes.data.domains[0]);
  await secondScreen();
  await expect(system().locator('.domain-entry-actions')).toHaveCount(0);
  await page.evaluate(() => { window.__miniFixture.failToolWrites = ['domains']; });
  await page.getByRole('button', { name: '上移成长领域', exact: true }).click();
  await expect(page.getByRole('button', { name: '重试领域排序', exact: true })).toBeVisible();
  const failed = (await read()).data;
  expect(failed.domains[0]).toEqual(legacyBytes.data.domains[0]);
  await page.evaluate(() => { window.__miniFixture.failToolWrites = []; });
  await page.getByRole('button', { name: '重试领域排序', exact: true }).click();
  await expect(page.getByRole('button', { name: '重试领域排序', exact: true })).toHaveCount(0);
  await expect.poll(async () => (await read()).data.domains[1].id).toBe('growth');
  expect((await read()).data.domains[0]).toEqual(legacyBytes.data.domains[0]);
};

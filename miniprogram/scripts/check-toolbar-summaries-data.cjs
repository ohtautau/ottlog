const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const { execFileSync } = require('node:child_process');
const { todoSeed, domainSeed, times } = require('./toolbar-summary-fixtures.cjs');
const modules = new Map();
function load(relative) {
  const filename = path.resolve(__dirname, relative);
  if (modules.has(filename)) return modules.get(filename);
  const exports = {}; modules.set(filename, exports);
  const code = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } }).outputText;
  new Function('exports', 'require', code)(exports, name => load(path.join(path.dirname(relative), `${name}.ts`)));
  return exports;
}
const { todoToolbarSummary, toggleTodo } = load('../src/lib/todo-data.ts');
const { domainToolbarSummary } = load('../src/lib/domain-completion.ts');
const domainData = load('../src/lib/domain-data.ts');
const clone = value => JSON.parse(JSON.stringify(value));
function freeze(value) { Object.freeze(value); for (const item of Object.values(value)) if (item && typeof item === 'object') freeze(item); return value; }
const now = new Date(2026, 9, 7, 12), next = new Date(2026, 9, 8, 0, 1);
const todos = freeze(todoSeed(now)), domains = freeze(domainSeed(now)), before = JSON.stringify([todos, domains]);
assert.equal(todoToolbarSummary(todos, now).completedToday, 2);
assert.equal(todoToolbarSummary(todos, now).recent.id, 'today-z');
assert.equal(todoToolbarSummary(todos, next).completedToday, 0);
assert.equal(todoToolbarSummary(todos, next).recent.id, 'today-z', 'New day retains the latest historical completed task');
let undone = toggleTodo(todos, 'today-z', now);
assert.equal(todoToolbarSummary(undone, now).completedToday, 1);
assert.equal(todoToolbarSummary(undone, now).recent.id, 'today-a');
undone = { ...undone, tasks: undone.tasks.filter(task => task.id !== 'today-a') };
assert.equal(todoToolbarSummary(undone, now).completedToday, 0);
assert.equal(todoToolbarSummary(undone, now).recent.id, 'old', 'Deleting the current completion falls back to yesterday');
undone = toggleTodo(undone, 'old', now);
assert.equal(todoToolbarSummary(undone, now).recent, undefined, 'Future and malformed completions never supply a recent title');
const completed = toggleTodo(undone, 'open', new Date(now.getTime() + 30000));
assert.equal(todoToolbarSummary(completed, new Date(now.getTime() + 30000)).completedToday, 1);
const tieTasks = { ...todos, tasks: todos.tasks.map(task => task.id === 'today-a' ? { ...task, completedAt: times(now).latest } : task) };
assert.equal(todoToolbarSummary(tieTasks, now).recent.id, 'today-z');
assert.equal(todoToolbarSummary({ ...tieTasks, tasks: [...tieTasks.tasks].reverse() }, now).recent.id, 'today-z', 'Task order cannot change a same-time recent completion');
assert.deepEqual(todoToolbarSummary({ ...todos, tasks: [] }, now), { completedToday: 0, recent: undefined });
assert.equal(domainToolbarSummary(domains, now).createdToday, 3, 'Both signs, every current domain and image-only records count');
assert.equal(domainToolbarSummary(domains, now).recentShortTermGoal.id, 'work-short');
assert.equal(domainToolbarSummary(domains, next).createdToday, 0);
assert.equal(domainToolbarSummary(domains, next).recentShortTermGoal.id, 'work-short', 'Record reset does not reset historical goal feedback');
let edited = clone(domains); edited.domains[0].positiveRecords[1].content = '今天修改了昨日记录';
assert.equal(domainToolbarSummary(edited, now).createdToday, 3, 'Editing content leaves original creation date/count intact');
edited = domainData.deleteDomainRecord(edited, 'work', 'positive', 'today-positive');
assert.equal(domainToolbarSummary(edited, now).createdToday, 2);
edited = domainData.addDomainRecord(edited, 'work', 'positive', '新的进展', new Date(now.getTime() + 30000));
assert.equal(domainToolbarSummary(edited, new Date(now.getTime() + 30000)).createdToday, 3);
const undoneGoal = domainData.undoDomainGoalCompletion(domains, 'work', 'shortTerm', 'work-short');
assert.equal(domainToolbarSummary(undoneGoal, now).recentShortTermGoal.id, 'life-short', 'Undo removes the goal from completed history');
const removedDomain = domainData.deleteDomain(domains, 'work');
assert.equal(domainToolbarSummary(removedDomain, now).createdToday, 1);
assert.equal(domainToolbarSummary(removedDomain, now).recentShortTermGoal.id, 'life-short');
const orphan = { ...removedDomain, completedGoals: [...removedDomain.completedGoals, domains.completedGoals.find(goal => goal.id === 'work-short')] };
assert.equal(domainToolbarSummary(orphan, now).recentShortTermGoal.id, 'life-short', 'Deleted-domain history cannot supply feedback');
const goalTie = { ...domains, completedGoals: domains.completedGoals.map(goal => goal.id === 'life-short' ? { ...goal, id: 'z-tie-goal', completedAt: times(now).yesterday } : goal) };
assert.equal(domainToolbarSummary(goalTie, now).recentShortTermGoal.id, 'z-tie-goal');
assert.equal(domainToolbarSummary({ ...goalTie, domains: [...goalTie.domains].reverse(), completedGoals: [...goalTie.completedGoals].reverse() }, now).recentShortTermGoal.id, 'z-tie-goal');
const invalidTime = { ...domains, completedGoals: [...domains.completedGoals, { ...domains.completedGoals[0], id: 'bad-time', completedAt: 'invalid' }, { ...domains.completedGoals[0], id: 'not-completed', status: 'active', completedAt: now.toISOString() }] };
assert.equal(domainToolbarSummary(invalidTime, now).recentShortTermGoal.id, 'work-short');
assert.deepEqual(domainToolbarSummary({ version: 1, domains: [], completedGoals: [] }, now), { createdToday: 0, recentShortTermGoal: undefined });
assert.equal(JSON.stringify([todos, domains]), before, 'Summary reads never mutate either source');
if (!process.argv.includes('--timezone')) for (const timezone of ['Asia/Singapore', 'America/New_York', 'UTC']) execFileSync(process.execPath, [__filename, '--timezone'], { env: { ...process.env, TZ: timezone }, stdio: 'inherit' });
console.log(`PASS toolbar summary data (${process.env.TZ || 'system timezone'}): local days, future/invalid timestamps, historical recency, stable ID ties, undo/delete, original record dates, image-only records and immutable reads.`);

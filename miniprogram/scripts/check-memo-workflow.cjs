const path = require('node:path');
const sharp = require('../../web/node_modules/sharp');
const { storageKey: homeShortcutKey, legacyLayout } = require('./home-shortcut-test-helpers.cjs');
const { expectReadableText } = require('./memo-readability.cjs');

module.exports = async function checkMemoWorkflow({ page, origin, out, width, expect }) {
  const image = (await sharp({ create: { width: 600, height: 360, channels: 3, background: '#b9dbca' } }).png().toBuffer()).toString('base64');
  const sheet = () => page.locator('.memo-sheet');
  const state = () => page.evaluate(() => window.__miniFixture.memoLocalState);
  const insert = () => page.getByRole('button', { name: '插入图片', exact: true });
  const close = async () => { await page.getByRole('button', { name: '关闭编辑', exact: true }).click(); await require('./confirm-unsaved-close.cjs')(page); };
  const goHome = () => page.evaluate(() => { location.hash = '#/pages/index/index'; });
  const goMemos = () => page.evaluate(() => { location.hash = '#/pages/memos/index'; });
  const create = () => page.locator('.entry-composer').getByRole('button', { name: '创建便签', exact: true });
  async function colorGrid() {
    const geometry = await sheet().locator('.memo-palette').evaluate(node => {
      const rect = node.getBoundingClientRect();
      return { width: rect.width, overflow: node.scrollWidth - node.clientWidth,
        options: [...node.querySelectorAll('button')].map(button => {
          const box = button.getBoundingClientRect();
          return { left: box.left - rect.left, right: box.right - rect.left, top: box.top - rect.top, bottom: box.bottom - rect.top, width: box.width };
        }) };
    });
    expect(geometry.options).toHaveLength(6);
    expect(geometry.overflow).toBeLessThanOrEqual(2);
    for (const [index, option] of geometry.options.entries()) {
      expect(Math.abs(option.width - geometry.options[0].width), `${width}: all color choices have equal widths`).toBeLessThanOrEqual(1);
      expect(option.width, `${width}: color choices keep 40px touch targets`).toBeGreaterThanOrEqual(40);
      expect(Math.abs(option.top - geometry.options[0].top), `${width}: six colors stay on one row`).toBeLessThanOrEqual(1);
      if (index) expect(option.left - geometry.options[index - 1].right).toBeCloseTo(6, 0);
    }
    expect(Math.abs(geometry.options[0].left)).toBeLessThanOrEqual(1);
    expect(Math.abs(geometry.options[5].right - geometry.width), 'The full row fills the palette width').toBeLessThanOrEqual(1);
    expect((await sheet().locator('.memo-palette button').allTextContents()).every(text => text === '' || text === '✓'), 'No color names appear inside the choices').toBe(true);
    return geometry;
  }
  await page.goto(`${origin}/?memo-workflow-${width}#/pages/posts/index`);
  await page.evaluate(({ homeShortcutKey, layout }) => {
    localStorage.setItem(homeShortcutKey, JSON.stringify(layout));
    window.__miniFixture.guestToolStates = { memos: { version: 1, notes: [] } }; location.hash = '#/pages/index/index';
  }, { homeShortcutKey, layout: legacyLayout(true) });
  await page.evaluate(data => { window.__miniFixture.memoImageBase64 = data; }, image);
  await page.getByRole('button', { name: '创建便签', exact: true }).click();
  await expect(sheet()).toBeVisible();
  await expect(sheet().getByRole('button', { name: '创建类型：备忘', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(sheet().locator('.tool-kicker')).toHaveCount(0);
  await expect(page.getByPlaceholder('准备记下什么？')).toBeVisible();
  await expect(sheet().locator('.memo-priority-trigger .priority-select-flag')).toHaveCSS('color', 'rgb(171, 208, 178)');
  await sheet().locator('.memo-priority-trigger').click();
  await expect(sheet().locator('.priority-option-mark')).toHaveCount(4);
  expect(await sheet().locator('.priority-option-mark').evaluateAll(nodes => nodes.map(node => getComputedStyle(node).color))).toEqual(['rgb(231, 160, 151)', 'rgb(228, 206, 133)', 'rgb(153, 184, 236)', 'rgb(171, 208, 178)']);
  await sheet().getByRole('button', { name: '优先度低', exact: true }).click();
  await expect(sheet().locator('.memo-priority-trigger .priority-select-flag')).toHaveCSS('color', 'rgb(153, 184, 236)');
  await expect(page.locator('.memo-body-input')).toHaveAttribute('placeholder', '写下内容…');
  await page.getByPlaceholder('准备记下什么？').fill('周末想做的事');
  await page.getByRole('button', { name: '生活', exact: true }).click();
  await expect(page.getByRole('button', { name: '生活', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: '选择现有标签', exact: true }).click();
  const tagPanel = page.locator('.memo-tags-field .form-popover-panel');
  await expect(tagPanel).toBeVisible();
  await expect(page.getByRole('textbox', { name: '便签标签' })).toHaveValue('生活');
  await page.getByRole('textbox', { name: '便签标签' }).fill('生活；旅行/灵感');
  await expect(tagPanel.getByRole('button', { name: '旅行', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(tagPanel.getByRole('button', { name: '灵感', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.screenshot({ path: path.join(out, `memo-tags-${width}.png`) });
  await tagPanel.getByRole('button', { name: '完成', exact: true }).click();
  await expect(tagPanel).toHaveCount(0);
  await page.locator('.memo-body-input').fill('**去散步**，记下沿途的小发现。');
  const fieldOrder = await sheet().evaluate(node => ({ title: node.querySelector('.memo-title-row').getBoundingClientRect().bottom, body: node.querySelector('.memo-body-input').getBoundingClientRect().top, tags: node.querySelector('.memo-tags-field').getBoundingClientRect().top }));
  expect(fieldOrder.body).toBeGreaterThanOrEqual(fieldOrder.title);
  expect(fieldOrder.tags).toBeGreaterThan(fieldOrder.body);
  const originalColorGrid = await colorGrid();
  await page.screenshot({ path: path.join(out, `memo-colors-${width}.png`) });
  const beforeColorSelection = await state();
  for (const color of ['雾蓝', '鼠尾草', '麦纸', '落日粉', '淡紫', '薄荷']) {
    await sheet().getByRole('button', { name: `使用${color}`, exact: true }).click();
    await expectReadableText(sheet().locator('.memo-title-input,.memo-body-input'), `${width}: ${color} creation input`, expect);
  }
  expect(await state(), 'Choosing any of the six draft colors does not write an unsaved memo').toEqual(beforeColorSelection);
  await page.getByRole('button', { name: '使用雾蓝', exact: true }).click();
  await expect(page.locator('.memo-color-options')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '使用雾蓝', exact: true })).toHaveAttribute('aria-pressed', 'true');
  expect(await colorGrid(), 'The selected state preserves every color option position and size').toEqual(originalColorGrid);
  await insert().click();
  await expect(page.locator('.memo-image')).toHaveCount(1);
  expect(await page.evaluate(() => window.__miniFixture.mediaOptions)).toMatchObject({ count: 1, mediaType: ['image'], sourceType: ['album', 'camera'] });
  await page.locator('.memo-image img').click();
  expect(await page.evaluate(() => window.__miniFixture.imagePreview.urls)).toHaveLength(1);
  const layout = await sheet().evaluate(node => {
    const rect = node.getBoundingClientRect(), viewport = document.querySelector('.preview-content').getBoundingClientRect();
    const footer = node.querySelector('.entry-footer,.memo-sheet-footer').getBoundingClientRect();
    return { top: rect.top, bottom: rect.bottom, viewportTop: viewport.top, viewportBottom: viewport.bottom, footerBottom: footer.bottom, overflow: node.scrollWidth - node.clientWidth };
  });
  expect(layout.top).toBeGreaterThanOrEqual(layout.viewportTop - 1);
  expect(layout.bottom).toBeLessThanOrEqual(layout.viewportBottom + 1);
  expect(layout.footerBottom).toBeLessThanOrEqual(layout.viewportBottom + 1);
  expect(layout.overflow).toBeLessThanOrEqual(2);
  await sheet().locator('.entry-scroll,.memo-sheet-scroll').evaluate(node => { node.scrollTop = 0; });
  await page.screenshot({ path: path.join(out, `memo-create-${width}.png`) });
  await page.getByRole('button', { name: '预览', exact: true }).click();
  await expect(page.locator('.memo-body-preview strong')).toHaveText('去散步');
  await expect(page.locator('.memo-images.is-preview img')).toHaveCount(1);
  await create().click();
  await expect(sheet()).toHaveCount(0);
  const saved = (await state()).notes[0];
  expect(saved.tags).toEqual(['生活', '旅行', '灵感']);
  expect(saved.color).toBe('blue');
  expect(saved.priority).toBe('low');
  expect(saved.images).toHaveLength(1);
  expect(saved.images[0].dataUrl).toBe(`data:image/png;base64,${image}`);
  await goMemos();
  await expect(page.locator('.memo-note-images img')).toHaveCount(1);
  await expect(page.locator('.memo-note .habit-priority')).toHaveCSS('border-top-color', 'rgb(153, 184, 236)');
  await goHome();
  await page.getByRole('button', { name: '创建便签', exact: true }).click();
  await expect(page.getByPlaceholder('准备记下什么？')).toHaveValue('');
  await expect(page.locator('.memo-image')).toHaveCount(0);
  await close();
  await goMemos();
  await page.getByRole('button', { name: '管理便签删除', exact: true }).click();
  await page.getByRole('button', { name: '查看便签：周末想做的事', exact: true }).click();
  await page.getByRole('button', { name: '编辑便签：周末想做的事', exact: true }).click();
  await expect(page.locator('.memo-sheet-title')).toHaveText('编辑便签');
  await expect(sheet().locator('.memo-priority-trigger .priority-select-flag')).toHaveCSS('color', 'rgb(153, 184, 236)');
  await sheet().locator('.memo-priority-trigger').click();
  await expect(sheet().locator('.priority-option[aria-pressed="true"]')).toHaveText('低优先度');
  await sheet().getByRole('button', { name: '优先度中', exact: true }).click();
  await expect(sheet().locator('.memo-priority-trigger .priority-select-flag')).toHaveCSS('color', 'rgb(228, 206, 133)');
  const beforeDismiss = await state();
  await page.getByPlaceholder('准备记下什么？').fill('收起后保留的便签输入');
  await page.locator('.memo-sheet-title').click();
  await expect(sheet()).toBeVisible();
  await page.evaluate(() => { window.__miniFixture.modalFailure = true; });
  await page.locator('.memo-backdrop').click({ position: { x: 8, y: 6 } });
  await require('./confirm-unsaved-close.cjs')(page);
  await expect(sheet()).toHaveCount(0);
  expect(await state(), 'Choosing not to save retains input without saving the memo').toEqual(beforeDismiss);
  await page.getByRole('button', { name: '查看便签：周末想做的事', exact: true }).click();
  await page.getByRole('button', { name: '编辑便签：周末想做的事', exact: true }).click();
  await expect(page.getByPlaceholder('准备记下什么？')).toHaveValue('收起后保留的便签输入');
  await page.getByPlaceholder('准备记下什么？').fill('周末想做的事');
  await page.evaluate(() => { window.__miniFixture.modalFailure = false; });
  await expect(page.locator('.memo-image img')).toHaveAttribute('src', saved.images[0].dataUrl);
  await expect(page.getByRole('button', { name: '生活', exact: true })).toHaveAttribute('aria-pressed', 'true');
  const editColorGrid = await colorGrid();
  await page.getByRole('button', { name: '使用薄荷', exact: true }).click();
  await expectReadableText(sheet().locator('.memo-title-input,.memo-body-input'), `${width}: mint original memo input`, expect);
  await sheet().getByRole('button', { name: '保存', exact: true }).click();
  expect((await state()).notes[0], 'The sixth color saves on the original memo').toMatchObject({ id: saved.id, color: 'mint' });
  await expect(page.getByRole('dialog', { name: '便签内容', exact: true })).toBeVisible();
  await expect(page.locator('.memo-color-trigger,.memo-reader .memo-editor-settings')).toHaveCount(0);
  await page.getByRole('button', { name: '编辑便签：周末想做的事', exact: true }).click();
  await expect(page.getByRole('button', { name: '使用薄荷', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: '使用鼠尾草', exact: true }).click();
  await expect(page.getByRole('button', { name: '使用鼠尾草', exact: true })).toHaveAttribute('aria-pressed', 'true');
  expect(await colorGrid(), 'The original memo editor also preserves the selected grid geometry').toEqual(editColorGrid);
  await page.screenshot({ path: path.join(out, `memo-edit-colors-${width}.png`) });
  await page.getByRole('button', { name: '移除图片 1', exact: true }).click();
  await sheet().getByRole('button', { name: '保存', exact: true }).click();
  expect((await state()).notes[0].images).toEqual([]);
  expect((await state()).notes[0].color, 'Selecting a color in the original editor persists on the same memo').toBe('sage');
  expect((await state()).notes[0], 'Priority editing retains the original memo ID').toMatchObject({ id: saved.id, priority: 'medium' });
  await expect(page.getByRole('dialog', { name: '便签内容', exact: true }).locator('.domain-record-images')).toHaveCount(0);
  await page.getByRole('dialog', { name: '便签内容', exact: true }).getByRole('button', { name: '完成', exact: true }).click();
  await expect(page.locator('.memo-note .habit-priority')).toHaveCSS('border-top-color', 'rgb(228, 206, 133)');

  // Image-only notes are saveable; cancelling and failed reads leave the draft intact.
  await goHome();
  await page.getByRole('button', { name: '创建便签', exact: true }).click();
  await page.evaluate(() => { window.__miniFixture.cancelChooseMedia = true; });
  const notices = await page.evaluate(() => window.__miniNotices.length);
  await insert().click();
  await expect(insert()).toBeEnabled();
  expect(await page.evaluate(() => window.__miniNotices.length)).toBe(notices);
  await expect(page.locator('.memo-image')).toHaveCount(0);
  await page.evaluate(() => { window.__miniFixture.cancelChooseMedia = false; window.__miniFixture.failImageRead = true; });
  await insert().click();
  await expect(insert()).toBeEnabled();
  await expect(page.locator('.memo-image')).toHaveCount(0);
  await page.evaluate(() => { window.__miniFixture.failImageRead = false; });
  await page.evaluate(() => { window.__miniFixture.memoImageBase64 = 'iVBORw0KGgo' + 'A'.repeat(300000); });
  await insert().click();
  await expect(insert()).toBeEnabled();
  await expect(page.locator('.memo-image')).toHaveCount(0);
  await expect(page.locator('.app-message')).toContainText('图片压缩后仍过大');
  await page.evaluate(data => { window.__miniFixture.memoImageBase64 = data; }, image);
  await insert().click();
  await expect(page.locator('.memo-image')).toHaveCount(1);
  await create().click();
  await expect(sheet()).toHaveCount(0);
  expect((await state()).notes).toHaveLength(2);
  expect((await state()).notes[0]).toMatchObject({ title: '', body: '', images: [{ dataUrl: `data:image/png;base64,${image}` }] });
};

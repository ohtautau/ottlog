const path = require('node:path');
const schedule = require('./todo-schedule-test-helpers.cjs');
module.exports = async function checkReminderSettings({ page, origin, out, width, expect }) {
  await page.clock.setFixedTime(new Date('2026-10-07T12:00:00'));
  await page.goto(`${origin}/?reminder-results-${width}#/pages/posts/index`);
  await page.evaluate(() => {
    document.documentElement.style.setProperty('--preview-safe-area-bottom', '34px');
    window.__miniFixture.sessionProfile = { authenticated: false, userName: null, isAdmin: false };
    window.__miniFixture.guestToolStates = { todos: { version: 1, tasks: [], categories: [] } };
    localStorage.removeItem('ottlog-mini-tool-v1:guest:todos'); location.hash = '#/pages/todos/index';
  });
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('ottlog-mini-tool-v1:guest:todos') || '{"data":{"tasks":[]}}').data.tasks);
  await page.locator('.todo-quadrant-later .todo-quadrant-add').click();
  await page.getByPlaceholder('准备做什么？').fill('提醒配置验证');
  await schedule.openSchedule(page, expect);
  await schedule.selectDate(page, '2028-03-31'); await schedule.setTime(page, 10, 0);
  await schedule.openSection(page, '设置重复'); await schedule.button(page, '每周').click();
  const row = () => schedule.button(page, '设置提醒');
  const parent = () => page.locator('.todo-schedule-reminder-popover');
  const day = () => parent().locator('.todo-schedule-reminder-days-inline [aria-pressed="true"]');
  const time = () => parent().locator('.is-reminders [aria-pressed="true"]');
  const customTime = () => parent().getByRole('button', { name: '设置提醒时刻', exact: true });
  const panel = () => page.locator('.todo-schedule-reminder-time');
  const hour = () => panel().getByLabel('提醒小时', { exact: true });
  const minute = () => panel().getByLabel('提醒分钟', { exact: true });
  const prompt = () => page.getByRole('dialog', { name: '保存修改？', exact: true });
  const done = () => panel().getByRole('button', { name: '完成提醒时间设置', exact: true });
  const overview = () => schedule.sheet(page).locator('.todo-schedule-calendar,.todo-schedule-row,.todo-reminder-clear').evaluateAll(nodes => nodes.map(node => { const box = node.getBoundingClientRect(); return [box.x, box.y, box.width, box.height]; }));
  await schedule.closeOptionWindows(page);
  const originalOverview = await overview();
  await schedule.openSection(page, '设置提醒');
  expect(await parent().locator('.is-reminders button').evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')))).toEqual(['准时', '提前10分钟', '提前30分钟', '提前1小时', '提前2小时', '设置提醒时刻']);
  await expect(parent().getByRole('button', { name: '不提醒', exact: true })).toHaveCount(0);
  await expect(parent().locator('.todo-schedule-reminder-preview')).toBeVisible();
  await expect(parent().locator('.todo-schedule-reminder-days-inline button')).toHaveCount(6);
  await expect(parent().locator('.todo-schedule-reminder-result')).toHaveCount(0);
  await expect(schedule.sheet(page).locator('.todo-schedule-row .select-chevron')).toHaveCount(0);
  await expect(schedule.button(page, '展开提醒设置')).toBeVisible();
  const checkUncovered = async popup => {
    await expect(popup).toBeVisible();
    const controls = await popup.evaluate(node => ({
      insideScroll: !!node.closest('.todo-schedule-scroll'), nestedPanel: !!node.parentElement.closest('.form-popover-panel'),
      hits: [...node.querySelectorAll('button')].map(button => { const box = button.getBoundingClientRect(); const hit = document.elementFromPoint(box.left + box.width / 2, box.top + box.height / 2); return button.contains(hit); }),
    }));
    expect(controls.insideScroll, 'Schedule choices are outside the main native scroll area').toBe(false);
    expect(controls.nestedPanel, 'Reminder child windows are outside their parent clipping panel').toBe(false);
    expect(controls.hits.every(Boolean), 'Every displayed option receives taps without a covering layer').toBe(true);
  };
  const expectNoInputFocus = async () => expect(await page.evaluate(() => document.activeElement?.matches('input,textarea'))).toBe(false);
  await expect(day()).toContainText('当天'); await expect(customTime()).toContainText('自定义时间');
  await expect(schedule.button(page, '清除提醒设置')).toHaveCount(0);
  await checkUncovered(parent()); await expectNoInputFocus();
  await parent().locator('.todo-schedule-reminder-days-inline').getByRole('button', { name: '前一天', exact: true }).click();
  await expect(schedule.button(page, '清除提醒设置'), 'Choosing only a day does not enable a default reminder').toHaveCount(0);
  await schedule.checkScheduleLayout(page, expect, `${width} default reminder`);
  for (const [name, clock, previousDay] of [['准时', '10:00', '前一天'], ['提前10分钟', '09:50', '前两天'], ['提前30分钟', '09:30', '前三天'], ['提前1小时', '09:00', '前一周'], ['提前2小时', '08:00', '前一月']]) {
    await parent().locator('.todo-schedule-reminder-days-inline').getByRole('button', { name: previousDay, exact: true }).click();
    await expect(day()).toContainText(previousDay);
    await parent().getByRole('button', { name, exact: true }).click();
    await expectNoInputFocus();
    await expect(day()).toContainText('当天'); await expect(time()).toContainText(name);
    await expect(row()).toContainText(`3月31日 ${clock}`);
    await expect(parent().locator('.todo-schedule-reminder-preview-value')).toHaveText(`2028年3月31日 ${clock}`);
    await expect(parent().locator('.is-reminders [aria-pressed="true"]')).toHaveAttribute('aria-label', name);
    expect(await overview(), 'Reminder selection does not move the calendar, settings or clear slot').toEqual(originalOverview);
  }
  await page.screenshot({ path: path.join(out, `reminder-result-quick-${width}.png`) });
  for (const [label, actual] of [['当天', '3月31日'], ['前一天', '3月30日'], ['前两天', '3月29日'], ['前三天', '3月28日'], ['前一周', '3月24日'], ['前一月', '2月29日']]) {
    await expect(parent().locator('.todo-schedule-reminder-days-inline button')).toHaveText(['当天', '前一天', '前两天', '前三天', '前一周', '前一月']);
    await schedule.checkScheduleLayout(page, expect, `${width} relative reminder days`);
    await checkUncovered(parent()); await expectNoInputFocus();
    if (label === '当天') await page.screenshot({ path: path.join(out, `reminder-result-days-${width}.png`) });
    await parent().locator('.todo-schedule-reminder-days-inline').getByRole('button', { name: label, exact: true }).click();
    await expect(day()).toContainText(label); await expect(time()).toContainText('提前2小时');
    await expect(row()).toContainText(`${actual} 08:00`);
    await expect(parent().locator('.todo-schedule-reminder-preview-value')).toHaveText(`2028年${actual} 08:00`);
    expect(await overview()).toEqual(originalOverview);
  }
  await parent().getByRole('button', { name: '提前10分钟', exact: true }).click();
  await expect(day()).toContainText('当天'); await expect(row()).toContainText('3月31日 09:50');
  await parent().locator('.todo-schedule-reminder-days-inline').getByRole('button', { name: '前一月', exact: true }).click();
  await expect(day()).toContainText('前一月'); await expect(row()).toContainText('2月29日 09:50');
  await expect(parent().locator('.todo-schedule-reminder-days-inline')).toBeVisible();
  await expect(parent().locator('.todo-schedule-reminder-preview')).toContainText('2028年2月29日 09:50');
  await customTime().click(); await expect(hour()).toHaveValue('09'); await expect(minute()).toHaveValue('50');
  await checkUncovered(panel()); await expectNoInputFocus();
  await panel().locator('.schedule-number-field').first().click({ position: { x: 3, y: 3 } }); await expect(hour()).toBeFocused();
  await schedule.checkScheduleLayout(page, expect, `${width} reminder clock`);
  const actionBox = await done().boundingBox();
  for (const [h, m] of [['', '00'], ['24', '00'], ['09', '60'], ['-1', '00'], ['1.5', '00']]) {
    await hour().fill(h); await minute().fill(m); await done().click();
    await expect(panel().getByRole('alert')).toContainText('0–23'); await expect(panel().getByRole('alert')).toBeInViewport({ ratio: 1 });
    await expect(hour()).toHaveValue(h); await expect(minute()).toHaveValue(m);
    expect(await done().boundingBox()).toEqual(actionBox); await expect(row()).toContainText('2月29日 09:50');
  }
  await page.screenshot({ path: path.join(out, `reminder-result-invalid-${width}.png`) });
  await hour().fill('17'); await minute().fill('45'); await page.keyboard.press('Escape');
  await expect(prompt()).toBeVisible(); await prompt().getByRole('button', { name: '继续编辑', exact: true }).click();
  await expect(hour()).toHaveValue('17'); await expect(minute()).toHaveValue('45');
  await panel().getByRole('button', { name: '关闭提醒时刻设置', exact: true }).click();
  await prompt().getByRole('button', { name: '不保存', exact: true }).click();
  await expect(panel()).toHaveCount(0); await expect(parent()).toBeVisible(); await expect(row()).toContainText('09:50');
  await customTime().click(); await expect(hour()).toHaveValue('17'); await expect(minute()).toHaveValue('45');
  await panel().getByRole('button', { name: '关闭提醒时刻设置', exact: true }).click();
  await prompt().getByRole('button', { name: '保存', exact: true }).click();
  await expect(time()).toContainText('17:45'); await expect(day()).toContainText('前一月');
  await expect(parent().locator('.is-reminders [aria-pressed="true"]')).toHaveAttribute('aria-label', '设置提醒时刻');
  await expect(row()).toContainText('2月29日 17:45');
  await schedule.checkScheduleLayout(page, expect, `${width} configured reminder`);
  const complete = parent().getByRole('button', { name: '完成提醒设置', exact: true });
  const authorize = parent().getByRole('button', { name: '开启微信提醒', exact: true });
  await expect(complete).toBeInViewport({ ratio: 1 }); await expect(authorize).toBeInViewport({ ratio: 1 }); await expect(authorize).toBeDisabled();
  await complete.click(); await expect(schedule.button(page, '清除提醒设置')).toBeVisible();
  await expect(schedule.button(page, '展开提醒设置')).toHaveCount(0);
  await expect(schedule.button(page, '清除提醒设置')).toHaveText('×');
  await expect(schedule.sheet(page).locator('.todo-schedule-clearable-row')).toHaveCount(3);
  const rowActions = await schedule.sheet(page).locator('.todo-schedule-clearable-row').evaluateAll(nodes => nodes.map(node => ({ buttons: node.querySelectorAll('button').length, action: (() => { const box = node.lastElementChild.getBoundingClientRect(); return [box.width, box.height]; })() })));
  expect(rowActions, 'Each settings row has one editor and one stable 40px arrow/clear action').toEqual(Array.from({ length: 3 }, () => ({ buttons: 2, action: [40, 40] })));
  await page.screenshot({ path: path.join(out, `reminder-result-row-${width}.png`) });
  await schedule.confirmSchedule(page, expect); expect(await stored()).toEqual([]);
  await page.locator('.entry-composer').getByRole('button', { name: '创建任务', exact: true }).click();
  await expect.poll(async () => (await stored()).length).toBe(1);
  const saved = (await stored())[0];
  const expectedReminder = await page.evaluate(() => new Date('2028-02-29T17:45:00').toISOString());
  expect(saved.reminderAt).toBe(expectedReminder); expect(saved.dueDate).toBe('2028-03-31'); expect(saved.dueTime).toBe('10:00'); expect(saved.recurrence.unit).toBe('week');
  // Creation returns to the list; editing uses the existing task entry.
  await page.getByRole('button', { name: '编辑任务：提醒配置验证', exact: true }).click();
  await schedule.openSchedule(page, expect);
  const editorOverview = await overview();
  await schedule.openSection(page, '设置提醒');
  await expect(day()).toContainText('前一月'); await expect(time()).toContainText('17:45');
  await parent().getByRole('button', { name: '准时', exact: true }).click();
  await expect(day()).toContainText('当天'); await expect(row()).toContainText('3月31日 10:00');
  expect((await stored())[0]).toEqual(saved);
  await schedule.closeSchedule(page, expect); await schedule.openSchedule(page, expect);
  await expect(row()).toContainText('2月29日 17:45');
  await schedule.setTime(page, 0, 5); await schedule.openSection(page, '设置提醒');
  await parent().getByRole('button', { name: '提前10分钟', exact: true }).click();
  await expect(day()).toContainText('当天'); await expect(row()).toContainText('3月30日 23:55');
  await page.screenshot({ path: path.join(out, `reminder-quick-reset-midnight-${width}.png`) });
  await schedule.closeSchedule(page, expect); await schedule.openSchedule(page, expect);
  await expect(row()).toContainText('2月29日 17:45'); expect((await stored())[0]).toEqual(saved);
  await schedule.button(page, '清除提醒设置').click();
  await expect(row()).toContainText('未设置'); await expect(schedule.button(page, '清除提醒设置')).toHaveCount(0);
  expect(await overview()).toEqual(editorOverview); expect((await stored())[0]).toEqual(saved);
  await schedule.closeSchedule(page, expect); await expect(page.locator('.todo-schedule-trigger')).toContainText('提醒');
  await schedule.openSchedule(page, expect); await expect(row()).toContainText('2月29日 17:45');
  await schedule.button(page, '清除提醒设置').click(); await schedule.confirmSchedule(page, expect);
  await page.locator('.todo-sheet:not(.entry-composer)').getByRole('button', { name: '保存', exact: true }).click();
  await expect.poll(async () => (await stored())[0].reminderAt).toBe(undefined);
  const cleared = (await stored())[0]; expect(cleared.id).toBe(saved.id); expect(cleared.dueDate).toBe(saved.dueDate); expect(cleared.dueTime).toBe(saved.dueTime); expect(cleared.recurrence).toEqual(saved.recurrence);
  await page.reload(); await page.getByRole('button', { name: '编辑任务：提醒配置验证', exact: true }).click();
  await schedule.openSchedule(page, expect); await expect(row()).toContainText('未设置'); await expect(schedule.button(page, '清除提醒设置')).toHaveCount(0);
  await schedule.openSection(page, '设置提醒'); await expect(day()).toContainText('当天'); await expect(customTime()).toContainText('自定义时间');
  await schedule.closeSchedule(page, expect); await page.getByRole('button', { name: '关闭编辑', exact: true }).click();
  await page.locator('.todo-quadrant-later .todo-quadrant-add').click();
  await page.getByPlaceholder('准备做什么？').fill('无日期提醒'); await schedule.openSchedule(page, expect);
  await schedule.openSection(page, '设置提醒');
  for (const name of ['准时', '提前10分钟', '提前30分钟', '提前1小时', '提前2小时']) {
    await parent().getByRole('button', { name, exact: true }).click();
    await expect(day()).toContainText('当天'); await expect(time()).toContainText(name);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const beforeComplete = await parent().getByRole('button', { name: '完成提醒设置', exact: true }).boundingBox();
    await parent().getByRole('button', { name: '完成提醒设置', exact: true }).click();
    await expect(parent().getByRole('alert')).toHaveText('还未设置具体时间');
    await expect(parent().getByRole('alert')).toBeInViewport({ ratio: 1 });
    expect(await parent().getByRole('button', { name: '完成提醒设置', exact: true }).boundingBox()).toEqual(beforeComplete);
    expect((await stored()).length).toBe(1);
  }
  await page.screenshot({ path: path.join(out, `reminder-missing-task-time-${width}.png`) });
  await schedule.closeOptionWindows(page); await schedule.button(page, '确认日期设置').click();
  await expect(schedule.sheet(page).getByRole('alert')).toHaveText('还未设置具体时间'); expect((await stored()).length).toBe(1);
  await schedule.openSection(page, '设置提醒'); await customTime().click();
  await hour().fill('23'); await minute().fill('59'); await done().click(); await schedule.confirmSchedule(page, expect);
  expect((await stored()).length).toBe(1);
  await page.locator('.entry-composer').getByRole('button', { name: '创建任务', exact: true }).click();
  await expect.poll(async () => (await stored()).length).toBe(2);
  const noDate = (await stored()).find(task => task.title === '无日期提醒');
  expect(noDate.dueDate).toBe(''); expect(noDate.dueTime).toBe(undefined);
  expect(noDate.reminderAt).toBe(await page.evaluate(() => new Date('2026-10-07T23:59:00').toISOString()));
  expect(await page.evaluate(() => window.__miniRequests.filter(request => request.path === '/wechat/reminders' && request.method === 'POST'))).toEqual([]);
  await expect(page.locator('.todo-sheet:not(.entry-composer)')).toHaveCount(0);
  await page.locator('.todo-quadrant-later .todo-quadrant-add').click();
  await page.getByPlaceholder('准备做什么？').fill('补齐任务时间提醒'); await schedule.openSchedule(page, expect);
  await schedule.selectDate(page, '2026-10-08'); await schedule.openSection(page, '设置提醒');
  await parent().getByRole('button', { name: '提前2小时', exact: true }).click();
  await parent().getByRole('button', { name: '设置任务时间', exact: true }).click();
  await expect(page.locator('.todo-schedule-time-popover')).toBeVisible();
  await schedule.sheet(page).getByLabel('任务小时', { exact: true }).fill('23');
  await schedule.sheet(page).getByLabel('任务分钟', { exact: true }).fill('00');
  await page.keyboard.press('Escape'); await expect(prompt()).toBeVisible();
  await prompt().getByRole('button', { name: '不保存', exact: true }).click();
  await schedule.button(page, '确认日期设置').click();
  await expect(schedule.sheet(page).getByRole('alert'), 'Unconfirmed time input does not satisfy reminder validation').toHaveText('还未设置具体时间');
  await schedule.setTime(page, 23, 0); await expect(row()).toContainText('10月8日 21:00');
  await schedule.button(page, '清除时间设置').click(); await schedule.button(page, '确认日期设置').click();
  await expect(schedule.sheet(page).getByRole('alert')).toHaveText('还未设置具体时间');
  await schedule.setTime(page, 10, 0); await expect(row()).toContainText('10月8日 08:00');
  await schedule.confirmSchedule(page, expect); expect((await stored()).length).toBe(2);
  await page.locator('.entry-composer').getByRole('button', { name: '创建任务', exact: true }).click();
  await expect.poll(async () => (await stored()).length).toBe(3);
  const repaired = (await stored()).find(task => task.title === '补齐任务时间提醒');
  expect(repaired.dueTime).toBe('10:00'); expect(repaired.dueDate).toBe('2026-10-08');
  expect(repaired.reminderAt).toBe(await page.evaluate(() => new Date('2026-10-08T08:00:00').toISOString()));
  await page.reload(); await page.getByRole('button', { name: '编辑任务：补齐任务时间提醒', exact: true }).click();
  await schedule.openSchedule(page, expect); await schedule.openSection(page, '设置提醒');
  await expect(day()).toContainText('当天'); await expect(time()).toContainText('提前2小时');
  await schedule.confirmSchedule(page, expect);
  expect((await stored()).find(task => task.id === repaired.id)).toEqual(repaired);
  if (width === 360) {
    const fold = await page.context().browser().newPage({ viewport: { width: 375, height: 667 }, timezoneId: 'America/New_York', reducedMotion: 'reduce' });
    try {
      await fold.clock.setFixedTime(new Date('2028-11-01T12:00:00Z'));
      await fold.goto(`${origin}/?reminder-fold#/pages/posts/index`);
      await fold.evaluate(() => { window.__miniFixture.guestToolStates = { todos: { version: 1, tasks: [], categories: [] } }; location.hash = '#/pages/todos/index'; });
      await fold.locator('.todo-quadrant-later .todo-quadrant-add').click(); await fold.getByPlaceholder('准备做什么？').fill('重复小时提醒');
      await schedule.openSchedule(fold, expect); await schedule.selectDate(fold, '2028-11-05'); await schedule.setTime(fold, 3, 30);
      await schedule.openSection(fold, '设置提醒'); await schedule.button(fold, '提前2小时').click();
      await expect(schedule.button(fold, '设置提醒')).toContainText('11月5日 01:30'); await schedule.confirmSchedule(fold, expect);
      await fold.locator('.entry-composer').getByRole('button', { name: '创建任务', exact: true }).click();
      await expect.poll(() => fold.evaluate(() => window.__miniFixture.todoLocalState?.tasks[0]?.reminderAt)).toBe('2028-11-05T06:30:00.000Z');
      await fold.getByRole('button', { name: '编辑任务：重复小时提醒', exact: true }).click();
      await schedule.openSchedule(fold, expect); await schedule.openSection(fold, '设置提醒');
      await expect(fold.locator('.is-reminders [aria-pressed="true"]')).toContainText('提前2小时');
      await schedule.confirmSchedule(fold, expect); await fold.locator('.todo-sheet:not(.entry-composer)').getByRole('button', { name: '保存', exact: true }).click();
      expect(await fold.evaluate(() => window.__miniFixture.todoLocalState.tasks[0].reminderAt)).toBe('2028-11-05T06:30:00.000Z');
    } finally { await fold.close(); }
  }
};

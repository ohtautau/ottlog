/* Exercise the shared Markdown editor through task creation and original editing. */
const path = require('node:path');
const sharp = require('../../web/node_modules/sharp');
module.exports = async function checkTodoNoteEditor({ page, origin, out, width, expect }) {
  const image = (await sharp({ create: { width: 480, height: 320, channels: 3, background: '#b9dbca' } }).png().toBuffer()).toString('base64');
  await page.goto(`${origin}/?todo-note-editor#/pages/posts/index`);
  await page.evaluate(data => {
    window.__miniFixture.guestToolStates = { todos: { version: 1, tasks: [], categories: [] }, memos: { version: 1, notes: [] } };
    window.__miniFixture.memoImageBase64 = data;
    location.hash = '#/pages/todos/index';
  }, image);
  const editor = () => page.locator('.todo-sheet');
  const note = () => editor().locator('.markdown-note-editor');
  const insert = () => note().getByRole('button', { name: '插入图片', exact: true });
  const body = () => editor().getByRole('textbox', { name: '任务备注', exact: true });
  const mode = type => editor().getByRole('button', { name: `创建类型：${type}`, exact: true });
  const stored = () => page.evaluate(() => window.__miniFixture.todoLocalState);
  async function checkDefaultPreview() {
    await expect(note().getByRole('button', { name: '预览', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await expect(note().getByRole('button', { name: '书写', exact: true })).toHaveAttribute('aria-pressed', 'false');
    await expect(note().locator('.memo-body-preview')).toBeVisible();
    await expect(body()).toHaveCount(0);
    await expect(note().getByRole('button', { name: /^移除图片/ })).toHaveCount(0);
  }
  await page.locator('.todo-quadrant-later .todo-quadrant-add').click();
  await editor().getByRole('textbox', { name: '任务名称', exact: true }).fill('带图的项目记录');
  await expect(body()).toBeVisible();
  for (const name of ['书写', '预览', '插入图片']) await expect(note().getByRole('button', { name, exact: true })).toBeInViewport({ ratio: 1 });
  await page.screenshot({ path: path.join(out, `todos-note-default-${width}.png`) });
  const markdown = '# 项目记录\n\n**关键进展**\n\n> 本周观察\n\n- 下一步行动\n\n```js\nconst next = "<step>";\n```\n\n' + Array.from({ length: 5 }, (_, i) => `第 ${i + 1} 段说明。`).join('\n\n');
  await body().fill(markdown);
  await note().getByRole('button', { name: '预览', exact: true }).click();
  await expect(note().locator('strong')).toHaveText('关键进展');
  await expect(note().locator('blockquote')).toContainText('本周观察');
  await expect(note().locator('.memo-body-preview')).toContainText('const next = "<step>";');
  await expect(note().locator('step'), 'Code is escaped as text in the existing WeChat-compatible renderer').toHaveCount(0);
  const preview = await note().locator('.memo-body-preview').evaluate(node => ({ height: node.getBoundingClientRect().height, clipped: node.scrollHeight - node.clientHeight }));
  expect(preview.height, 'Long Markdown previews grow to display all paragraphs').toBeGreaterThan(100);
  expect(preview.clipped, 'The shared preview never clips the rendered body').toBeLessThanOrEqual(2);
  await insert().click();
  await expect(note().locator('.memo-image')).toHaveCount(1);
  await note().locator('.memo-image img').click();
  expect(await page.evaluate(() => window.__miniFixture.imagePreview.urls)).toHaveLength(1);
  await page.screenshot({ path: path.join(out, `todos-note-preview-${width}.png`) });
  await mode('备忘').click();
  await expect(editor().getByRole('textbox', { name: '便签内容', exact: true })).toHaveValue(markdown);
  await expect(note().locator('.memo-image img')).toHaveAttribute('src', `data:image/png;base64,${image}`);
  await mode('任务').click();
  await expect(body()).toHaveValue(markdown);
  await note().getByRole('button', { name: '移除图片 1', exact: true }).click();
  await mode('备忘').click();
  await expect(note().locator('.memo-image')).toHaveCount(0);
  await mode('任务').click();
  await insert().click();
  await expect(note().locator('.memo-image')).toHaveCount(1);
  await editor().getByRole('button', { name: '关闭编辑', exact: true }).click();
  await require('./confirm-unsaved-close.cjs')(page);
  const cached = await page.evaluate(() => window.__miniPreviewControl.readStorage('ottlog-mini-entry-draft-v1:guest'));
  expect(JSON.stringify(cached).split(image).length - 1, 'The shared attachment is stored once in the creation draft').toBe(1);
  await page.locator('.todo-quadrant-later .todo-quadrant-add').click();
  await expect(body()).toHaveValue(markdown);
  await expect(note().locator('.memo-image img')).toHaveAttribute('src', `data:image/png;base64,${image}`);
  await editor().getByRole('button', { name: '创建任务', exact: true }).click();
  await expect(editor()).toHaveCount(0);
  const saved = (await stored()).tasks[0];
  expect(saved.description).toBe(markdown);
  expect(saved.images).toHaveLength(1);
  expect(saved.images[0].dataUrl).toBe(`data:image/png;base64,${image}`);
  await page.getByRole('button', { name: '编辑任务：带图的项目记录', exact: true }).click();
  await checkDefaultPreview();
  await expect(note().locator('strong')).toHaveText('关键进展');
  await expect(note().locator('.memo-body-preview')).toContainText('第 5 段说明。');
  await page.screenshot({ path: path.join(out, `todos-note-open-preview-${width}.png`) });
  await note().locator('.memo-image img').click();
  const openedImage = await page.evaluate(() => window.__miniFixture.imagePreview);
  expect(openedImage.urls).toHaveLength(1);
  expect(openedImage.current).toBe(openedImage.urls[0]);
  expect(openedImage.urls[0]).toMatch(/\/ottlog-memo-preview-0$/);
  expect((await stored()).tasks[0]).toEqual(saved);
  await note().getByRole('button', { name: '书写', exact: true }).click();
  await editor().getByRole('button', { name: '关闭编辑', exact: true }).click();
  await expect(editor()).toHaveCount(0);
  expect((await stored()).tasks[0]).toEqual(saved);
  await page.getByRole('button', { name: '编辑任务：带图的项目记录', exact: true }).click();
  await checkDefaultPreview();
  await note().getByRole('button', { name: '书写', exact: true }).click();
  await expect(body()).toHaveValue(markdown);
  await expect(note().locator('.memo-image img')).toHaveAttribute('src', saved.images[0].dataUrl);
  // Failed/cancelled native selection leaves the saved attachment and text intact.
  for (const failure of ['cancelChooseMedia', 'failImageRead']) {
    await page.evaluate(key => { window.__miniFixture[key] = true; }, failure);
    await insert().click();
    await expect(insert()).toBeEnabled();
    await expect(note().locator('.memo-image')).toHaveCount(1);
    await expect(body()).toHaveValue(markdown);
    await page.evaluate(key => { window.__miniFixture[key] = false; }, failure);
  }
  await body().fill(markdown + '\n\n**更新备注**');
  if (width === 360) {
    await page.evaluate(() => { window.__miniFixture.failToolWrites = ['todos']; });
    await editor().getByRole('button', { name: '保存', exact: true }).click();
    await expect(body(), 'A failed local write retains the original editor and Markdown draft').toHaveValue(markdown + '\n\n**更新备注**');
    await expect(note().locator('.memo-image img')).toHaveAttribute('src', saved.images[0].dataUrl);
    expect((await stored()).tasks[0].description).toBe(markdown);
    await page.evaluate(() => { window.__miniFixture.failToolWrites = []; });
  }
  await editor().getByRole('button', { name: '保存', exact: true }).click();
  expect((await stored()).tasks).toHaveLength(1);
  expect((await stored()).tasks[0]).toMatchObject({ id: saved.id, images: saved.images, description: markdown + '\n\n**更新备注**' });
  await page.getByRole('button', { name: '编辑任务：带图的项目记录', exact: true }).click();
  await checkDefaultPreview();
  await expect(note().locator('strong')).toContainText(['关键进展', '更新备注']);
  await note().getByRole('button', { name: '书写', exact: true }).click();
  await note().getByRole('button', { name: '移除图片 1', exact: true }).click();
  await editor().getByRole('button', { name: '保存', exact: true }).click();
  expect((await stored()).tasks[0].images).toEqual([]);
  await page.getByRole('button', { name: '编辑任务：带图的项目记录', exact: true }).click();
  await checkDefaultPreview();
  await expect(note().locator('.memo-image')).toHaveCount(0);
  await editor().getByRole('button', { name: '关闭编辑', exact: true }).click();
  await require('./confirm-unsaved-close.cjs')(page);
  if (width !== 360) return;
  // A pending native picker must neither submit nor attach to another account.
  await page.locator('.todo-quadrant-later .todo-quadrant-add').click();
  await editor().getByRole('textbox', { name: '任务名称', exact: true }).fill('尚在选择图片');
  await page.evaluate(() => { window.__miniFixture.deferChooseMedia = true; });
  await insert().click();
  await expect(editor().getByRole('button', { name: '创建任务', exact: true })).toBeDisabled();
  await expect(editor().getByRole('button', { name: '关闭编辑', exact: true })).toBeDisabled();
  await expect(mode('备忘')).toBeDisabled();
  await expect(body()).toBeDisabled();
  await page.evaluate(() => {
    window.__miniFixture.accountToolStates = { 'note-reader': { todos: { version: 1, tasks: [], categories: [] }, memos: { version: 1, notes: [] } } };
    window.__miniFixture.sessionProfile = { authenticated: true, userName: 'note-reader', isAdmin: false };
    window.__miniPreviewControl.emit('ottlog-session');
  });
  await expect(editor()).toHaveCount(0);
  await page.evaluate(() => { window.__miniFixture.deferChooseMedia = false; window.__miniFixture.resolveChooseMedia(); });
  await page.locator('.todo-quadrant-later .todo-quadrant-add').click();
  await expect(body()).toHaveValue('');
  await expect(note().locator('.memo-image')).toHaveCount(0);
  await editor().getByRole('button', { name: '关闭编辑', exact: true }).click();
  await require('./confirm-unsaved-close.cjs')(page);
};

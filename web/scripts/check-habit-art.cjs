const { chromium, expect } = require('@playwright/test');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { origin } = JSON.parse(fs.readFileSync('test-results/productivity-runtime.json'));
(async () => {
  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({ viewport: { width: 1920, height: 1080 } });
    const page = await context.newPage();
    const failures = [];
    page.on('pageerror', error => failures.push(error.message));
    await page.goto(origin + '/daily');
    const cards = page.locator('[data-habit]');
    await expect(cards).toHaveCount(24);
    await expect(page.getByRole('button', { name: /数据导入/ })).toBeEnabled();
    assert.equal(await cards.first().locator('[data-static=true]').count(), 1);
    await expect(cards.first().locator('button').first().locator('img')).toHaveAttribute('src', '/habit-icons/exercise.svg');
    const colours = await cards.evaluateAll(items => [...new Set(items.map(item => getComputedStyle(item).getPropertyValue('--habit-color')))]);
    assert.equal(colours.length, 5);
    await expect(cards.first().getByRole('button', { name: /周/ })).toHaveCount(7);
    const firstDay = cards.first().getByRole('button', { name: /周/ }).first();
    await firstDay.click(); await expect(firstDay).toHaveAttribute('aria-pressed', 'true');
    await page.reload(); await expect(cards.first().getByRole('button', { name: /周/ }).first()).toHaveAttribute('aria-pressed', 'true');
    await cards.first().getByRole('button', { name: /周/ }).first().click();
    await expect(cards.first().getByRole('button', { name: /周/ }).first()).toHaveAttribute('aria-pressed', 'false');
    await cards.first().scrollIntoViewIfNeeded();
    await page.screenshot({ path: 'test-results/habits-collection-wide.png' });

    await page.getByRole('button', { name: '管理提醒 +' }).click();
    const editor = page.locator('form').filter({ has: page.getByRole('heading', { name: '加一件想记起的事' }) });
    await editor.getByText('选择主题插画', { exact: false }).click();
    const gallery = editor.getByRole('group', { name: '主题插画图库' });
    await expect(gallery.getByRole('button')).toHaveCount(30);
    const staticAnimations = await gallery.locator('[data-static=true] *').evaluateAll(elements => elements.filter(e => getComputedStyle(e).animationName !== 'none').length);
    assert.equal(staticAnimations, 0);
    await gallery.getByRole('button', { name: '选择照顾植物插画', exact: true }).click();
    await expect(editor.locator('[class*="scenePreview"] [data-scene]')).toHaveAttribute('data-scene', 'plant');
    const download = page.waitForEvent('download');
    await editor.getByRole('button', { name: '下载静态图', exact: true }).click();
    const asset = await download; assert.equal(asset.suggestedFilename(), 'ottlog-habit-plant.svg');
    await asset.saveAs('test-results/habit-plant-static.svg');
    await gallery.scrollIntoViewIfNeeded(); await page.screenshot({ path: 'test-results/habits-gallery-wide.png' });
    await editor.locator('input[name=title]').fill('测试照顾植物');
    await editor.getByLabel('提醒自己的话').fill('看看植物的土壤。');
    const image = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 600; canvas.height = 400; const c = canvas.getContext('2d'); c.fillStyle = '#548775'; c.fillRect(0, 0, 600, 400); c.fillStyle = '#efd7a4'; c.fillRect(70, 70, 120, 120); return canvas.toDataURL('image/png'); });
    await editor.getByLabel('上传习惯背景图片').setInputFiles({ name: 'plant.png', mimeType: 'image/png', buffer: Buffer.from(image.split(',')[1], 'base64') });
    await expect(editor.getByRole('status')).toContainText('已选择 plant.png');
    await editor.getByRole('button', { name: '保存提醒', exact: true }).click();
    const custom = cards.filter({ has: page.getByRole('button', { name: '测试照顾植物', exact: true }) });
    await expect(custom).toHaveCount(1);
    const customBackground = custom.locator('[class*="routineArt"] > img');
    await expect(customBackground).toHaveAttribute('src', /^data:image\/(webp|png);base64,/);
    const source = await customBackground.getAttribute('src');
    assert(source.length <= 8192);
    await custom.getByRole('button', { name: '编辑', exact: true }).click();
    await page.locator('form').getByText('选择主题插画', { exact: false }).click();
    await page.getByRole('button', { name: '选择喝水插画', exact: true }).click();
    await page.locator('form').getByRole('button', { name: '保存提醒', exact: true }).click();
    assert.equal(await customBackground.getAttribute('src'), source);
    await page.reload(); await expect(customBackground).toHaveAttribute('src', source);
    await page.getByRole('button', { name: /数据导入/ }).click();
    const backupPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: /导出 JSON/ }).click();
    const backup = await backupPromise; await backup.saveAs('test-results/habit-art-backup.json');
    const data = JSON.parse(fs.readFileSync('test-results/habit-art-backup.json')).data;
    assert.equal(data.items.find(item => item.title === '测试照顾植物').backgroundImage, source);
    await page.evaluate(() => {
      const key = 'ottlog-tool-v1:guest:reminders';
      localStorage.setItem(key, JSON.stringify({ data: { version: 1, items: [], done: {} }, pending: false }));
      window.dispatchEvent(new CustomEvent('ottlog-tool-cache', { detail: key }));
    });
    await expect(cards).toHaveCount(0);
    await page.getByLabel('选择备份文件').setInputFiles('test-results/habit-art-backup.json');
    await expect(page.getByRole('button', { name: '确认导入', exact: true })).toBeEnabled();
    await page.getByRole('button', { name: '确认导入', exact: true }).click();
    await expect(page.getByText('导入已应用，保存与账号同步状态见下方。')).toBeVisible();
    await page.getByLabel('关闭数据备份').click();
    await expect(cards).toHaveCount(25);
    await expect(customBackground).toHaveAttribute('src', source);
    await page.reload();
    await expect(customBackground).toHaveAttribute('src', source);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.locator('[data-scene] *').evaluateAll(elements => elements.filter(e => getComputedStyle(e).animationName !== 'none').length), 0);
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 844 });
      await page.getByRole('button', { name: '习惯与打卡', exact: true }).click();
      await cards.first().scrollIntoViewIfNeeded();
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.screenshot({ path: `test-results/habits-collection-${width}.png` });
      await page.getByRole('button', { name: '管理提醒 +' }).click();
      await page.locator('form').scrollIntoViewIfNeeded();
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.getByRole('button', { name: '收起管理 −' }).click();
    }
    assert.deepEqual(failures, []);
    console.log('PASS: 30 art themes/static SVGs, 30 logos, five group colours, editable week history, custom local image/save/reload/keep on theme change, static download, backup export/import, reduced motion, 1920/390/320 layouts.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });

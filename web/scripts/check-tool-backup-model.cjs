const assert = require('node:assert/strict');
const { fixtures, load, createToolBackup, parseToolBackup, importToolData, validateToolData, maximumBackupBytes } = require('./tool-backup-fixtures.cjs');
const a = fixtures('one'), b = fixtures('two');
for (const key of Object.keys(a)) {
  const file = createToolBackup(key, a[key]);
  assert.deepEqual(parseToolBackup('\uFEFF' + JSON.stringify(file), key).data, a[key]);
  assert.deepEqual(importToolData(key, a[key], a[key], 'merge'), a[key]);
  const merged = importToolData(key, a[key], b[key], 'merge');
  assert.deepEqual(importToolData(key, merged, b[key], 'merge'), merged);
  assert.deepEqual(importToolData(key, merged, a[key], 'replace'), a[key]);
  assert.throws(() => parseToolBackup(JSON.stringify({ ...file, tool: key === 'memos' ? 'todos' : 'memos' }), key), /其他工具/);
  assert.throws(() => parseToolBackup(JSON.stringify({ ...file, version: 22 }), key), /版本/);
  assert.throws(() => validateToolData(key, { ...a[key], version: 7 }));
}
const todos = importToolData('todos', a.todos, b.todos, 'merge');
assert.equal(todos.categories.length, 1);
assert(todos.tasks.every(task => task.categoryId === 'category-one'));
const reminders = importToolData('reminders', a.reminders, b.reminders, 'merge');
assert.deepEqual(reminders.done['2026-09-09'], ['reminder-one', 'reminder-two']);
const duplicate = structuredClone(a.todos); duplicate.tasks.push(duplicate.tasks[0]);
assert.throws(() => validateToolData('todos', duplicate));
assert.throws(() => validateToolData('todos', { ...a.todos, tasks: [{ ...a.todos.tasks[0], categoryId: 'missing' }] }));
assert.throws(() => validateToolData('reminders', { ...a.reminders, done: { '2026-02-31': ['reminder-one'] } }));
assert.throws(() => validateToolData('memos', { ...a.memos, notes: [{ ...a.memos.notes[0], body: 'x'.repeat(6001) }] }));
const full = { ...a.memos, notes: Array.from({ length: 50 }, (_, i) => ({ ...a.memos.notes[0], id: 'full-' + i })) };
assert.throws(() => importToolData('memos', full, b.memos, 'merge'));
assert.equal(full.notes.length, 50);
const nearPayload = { ...a.meals, meals: Array.from({ length: 150 }, (_, i) => ({ ...a.meals.meals[0], id: 'large-' + i, name: '餐'.repeat(60), place: '店'.repeat(100), note: '字'.repeat(200) })) };
assert.throws(() => validateToolData('meals', nearPayload), /128 KB/);
assert.throws(() => parseToolBackup(' '.repeat(maximumBackupBytes + 1), 'todos'), /8 MB/);
assert.throws(() => parseToolBackup('{broken', 'todos'), /JSON/);
const now = Date.parse('2026-09-09T10:00:00.000Z');
const { startTimer } = load('app/pomodoro/pomodoro-data.ts');
const running = startTimer(a.pomodoro, now, 'active', { taskId: 'todo-one', title: '专注事项' });
const exported = createToolBackup('pomodoro', running, new Date(now + 30_000));
assert.equal(exported.data.active.running, false);
assert.equal(exported.data.active.remainingSeconds, 1470);
assert.equal(running.active.running, true);
assert.throws(() => importToolData('pomodoro', running, b.pomodoro, 'replace'), /结束或重置/);
const timerMerged = importToolData('pomodoro', running, { ...b.pomodoro, settings: { ...b.pomodoro.settings, focus: 5 } }, 'merge');
assert.deepEqual(timerMerged.active, running.active);
assert.equal(timerMerged.settings.focus, 25);
assert.equal(timerMerged.sessions.length, 2);
console.log('PASS model: all five round trips; idempotent merge; categories and history; malformed, duplicate, oversized and wrong-tool rejection; no partial writes; paused timer snapshot and active timer protection.');
